-- 0006_ai_events.sql — durable event log, per-consumer deliveries and dead letters.
--
-- Forward-only. Applied in a single transaction by scripts/migrate.sh.
--
-- Producer-side outbox: AI events are appended to `ai.events` and delivered to
-- consumers at-least-once. `ai.event_deliveries` records idempotent processing
-- per consumer group; failures retry with a bounded attempt count and are moved
-- to `ai.event_dead_letters` when exhausted. Kafka (when enabled) mirrors this
-- log; the enterprise event bus remains authoritative for enterprise events.

CREATE TABLE IF NOT EXISTS ai.events (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id       uuid        NOT NULL UNIQUE,
  type           text        NOT NULL,
  version        text        NOT NULL,
  tenant_id      bigint      NOT NULL,
  source         text        NOT NULL DEFAULT 'ai-api',
  actor_id       bigint,
  subject_type   text,
  subject_id     text,
  correlation_id text,
  request_id     text,
  idempotency_key text,
  payload        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  occurred_at    timestamptz NOT NULL DEFAULT now(),
  published_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS events_tenant_created_idx ON ai.events (tenant_id, id DESC);
CREATE INDEX IF NOT EXISTS events_type_idx ON ai.events (type);
-- Idempotent publication for events that carry a producer-supplied key.
CREATE UNIQUE INDEX IF NOT EXISTS events_idempotency_uniq
  ON ai.events (type, idempotency_key) WHERE idempotency_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS ai.event_deliveries (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id       uuid        NOT NULL REFERENCES ai.events(event_id) ON DELETE CASCADE,
  consumer_group text        NOT NULL,
  status         text        NOT NULL DEFAULT 'pending',
  attempts       integer     NOT NULL DEFAULT 0,
  last_error     text,
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT event_deliveries_uniq UNIQUE (event_id, consumer_group),
  CONSTRAINT event_deliveries_status_chk
    CHECK (status IN ('pending', 'delivered', 'failed', 'dead'))
);
CREATE INDEX IF NOT EXISTS event_deliveries_group_status_idx
  ON ai.event_deliveries (consumer_group, status);

CREATE TABLE IF NOT EXISTS ai.event_dead_letters (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id       uuid        NOT NULL,
  consumer_group text        NOT NULL,
  attempts       integer     NOT NULL DEFAULT 0,
  last_error     text,
  payload        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS event_dead_letters_group_idx
  ON ai.event_dead_letters (consumer_group, created_at DESC);

COMMENT ON TABLE ai.events IS 'Durable AI event log (versioned envelopes; outbox).';
COMMENT ON TABLE ai.event_deliveries IS 'Per-consumer-group delivery state (idempotency + retries).';
COMMENT ON TABLE ai.event_dead_letters IS 'Events that exhausted their retry budget.';

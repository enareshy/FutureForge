-- 0024_stage8_product_bom.sql — Product & BOM Intelligence (Step 6).
--
-- Additive only. Adds tenant-scoped product/part, revision, BOM header/line and
-- EBOM->MBOM transformation/reconciliation records. These are *domain* records
-- that live alongside the Stage 7 knowledge graph: each row may carry a
-- `graph_entity_id` pointing at the graph entity that represents it, so the
-- digital thread, traversal and change-impact engines keep working without a
-- second graph model.
--
-- Identity:
--   * product_items        UNIQUE (tenant_id, item_type, item_key)
--   * product_revisions    UNIQUE (tenant_id, item_id, revision)
--   * bom_headers          UNIQUE (tenant_id, bom_type, bom_key)
--   * bom_lines            UNIQUE (tenant_id, bom_header_id, line_key)
--       where `line_key` is the caller/service supplied stable identity within a
--       parent BOM. Reordering does not change it, so a moved line is the same
--       line during comparison.
--
-- Transformation proposals are stored separately from authoritative BOM lines:
-- a run/entry never mutates `bom_lines`; promotion is a deliberate, audited
-- action performed by the BOM service (which itself does not overwrite an
-- enterprise system of record).
--
-- RLS: every table carries an explicit tenant_id and reuses the same FORCE ROW
-- LEVEL SECURITY policy as the rest of the `ai` schema.

-- --- Product / part / assembly master -----------------------------------
CREATE TABLE IF NOT EXISTS ai.product_items (
  id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  item_type         text        NOT NULL DEFAULT 'part',
  item_key          text        NOT NULL,
  name              text,
  description       text,
  unit_of_measure   text        NOT NULL DEFAULT 'EA',
  lifecycle_status  text        NOT NULL DEFAULT 'active',
  configuration     jsonb       NOT NULL DEFAULT '{}'::jsonb,
  variants          jsonb       NOT NULL DEFAULT '[]'::jsonb,
  effectivity_from  timestamptz,
  effectivity_to    timestamptz,
  external_id       text,
  source_system     text,
  source_ref        text,
  classification    text        NOT NULL DEFAULT 'internal',
  acl               jsonb       NOT NULL DEFAULT '{}'::jsonb,
  graph_entity_id   bigint,
  version           integer     NOT NULL DEFAULT 1,
  created_by        text,
  updated_by        text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  deleted_at        timestamptz,
  CONSTRAINT product_items_identity_uniq UNIQUE (tenant_id, item_type, item_key),
  CONSTRAINT product_items_type_chk CHECK (item_type IN
    ('product', 'part', 'assembly', 'component', 'material')),
  CONSTRAINT product_items_lifecycle_chk CHECK (lifecycle_status IN
    ('draft', 'active', 'released', 'obsolete', 'archived')),
  CONSTRAINT product_items_version_chk CHECK (version >= 1)
);
CREATE INDEX IF NOT EXISTS product_items_lookup_idx
  ON ai.product_items (tenant_id, item_type, lifecycle_status)
  WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS product_items_name_idx
  ON ai.product_items (tenant_id, lower(item_key))
  WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS product_items_external_idx
  ON ai.product_items (tenant_id, source_system, external_id)
  WHERE external_id IS NOT NULL;

-- --- Product / part revisions -------------------------------------------
CREATE TABLE IF NOT EXISTS ai.product_revisions (
  id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  item_id           bigint      NOT NULL REFERENCES ai.product_items(id) ON DELETE CASCADE,
  revision          text        NOT NULL,
  lifecycle_status  text        NOT NULL DEFAULT 'draft',
  effectivity_from  timestamptz,
  effectivity_to    timestamptz,
  configuration     jsonb       NOT NULL DEFAULT '{}'::jsonb,
  external_id       text,
  source_system     text,
  source_ref        text,
  classification    text        NOT NULL DEFAULT 'internal',
  acl               jsonb       NOT NULL DEFAULT '{}'::jsonb,
  graph_entity_id   bigint,
  version           integer     NOT NULL DEFAULT 1,
  created_by        text,
  updated_by        text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  deleted_at        timestamptz,
  CONSTRAINT product_revisions_identity_uniq UNIQUE (tenant_id, item_id, revision),
  CONSTRAINT product_revisions_lifecycle_chk CHECK (lifecycle_status IN
    ('draft', 'active', 'released', 'obsolete', 'archived')),
  CONSTRAINT product_revisions_version_chk CHECK (version >= 1)
);
CREATE INDEX IF NOT EXISTS product_revisions_item_idx
  ON ai.product_revisions (tenant_id, item_id, created_at DESC)
  WHERE deleted_at IS NULL;

-- --- BOM headers ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS ai.bom_headers (
  id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  bom_type          text        NOT NULL DEFAULT 'EBOM',
  bom_key           text        NOT NULL,
  name              text,
  description       text,
  root_item_id      bigint      REFERENCES ai.product_items(id) ON DELETE SET NULL,
  root_revision_id  bigint      REFERENCES ai.product_revisions(id) ON DELETE SET NULL,
  plant             text,
  configuration     jsonb       NOT NULL DEFAULT '{}'::jsonb,
  lifecycle_status  text        NOT NULL DEFAULT 'draft',
  external_id       text,
  source_system     text,
  source_ref        text,
  classification    text        NOT NULL DEFAULT 'internal',
  acl               jsonb       NOT NULL DEFAULT '{}'::jsonb,
  graph_entity_id   bigint,
  version           integer     NOT NULL DEFAULT 1,
  created_by        text,
  updated_by        text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  deleted_at        timestamptz,
  CONSTRAINT bom_headers_identity_uniq UNIQUE (tenant_id, bom_type, bom_key),
  CONSTRAINT bom_headers_type_chk CHECK (bom_type IN ('EBOM', 'MBOM', 'BOP', 'OTHER')),
  CONSTRAINT bom_headers_lifecycle_chk CHECK (lifecycle_status IN
    ('draft', 'in_review', 'released', 'superseded', 'obsolete', 'archived')),
  CONSTRAINT bom_headers_version_chk CHECK (version >= 1)
);
CREATE INDEX IF NOT EXISTS bom_headers_root_idx
  ON ai.bom_headers (tenant_id, root_item_id, bom_type)
  WHERE deleted_at IS NULL;

-- --- BOM lines -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS ai.bom_lines (
  id                    bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id             bigint      NOT NULL,
  bom_header_id         bigint      NOT NULL REFERENCES ai.bom_headers(id) ON DELETE CASCADE,
  parent_revision_id    bigint      NOT NULL REFERENCES ai.product_revisions(id) ON DELETE CASCADE,
  child_item_id         bigint      NOT NULL REFERENCES ai.product_items(id) ON DELETE RESTRICT,
  child_revision_id     bigint      REFERENCES ai.product_revisions(id) ON DELETE SET NULL,
  line_key              text        NOT NULL,
  quantity              numeric(20,6) NOT NULL DEFAULT 1,
  unit_of_measure       text        NOT NULL DEFAULT 'EA',
  find_number           text,
  sequence              integer     NOT NULL DEFAULT 0,
  reference_designators jsonb       NOT NULL DEFAULT '[]'::jsonb,
  usage                 text        NOT NULL DEFAULT 'DESIGN',
  line_status           text        NOT NULL DEFAULT 'active',
  is_phantom            boolean     NOT NULL DEFAULT false,
  is_reference          boolean     NOT NULL DEFAULT false,
  alternate_of_line_id  bigint      REFERENCES ai.bom_lines(id) ON DELETE SET NULL,
  substitute_for_item_id bigint     REFERENCES ai.product_items(id) ON DELETE SET NULL,
  plant                 text,
  effectivity_from      timestamptz,
  effectivity_to        timestamptz,
  configuration         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  attributes            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  source_system         text,
  source_ref            text,
  external_id           text,
  version               integer     NOT NULL DEFAULT 1,
  created_by            text,
  updated_by            text,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  deleted_at            timestamptz,
  CONSTRAINT bom_lines_quantity_chk CHECK (quantity > 0),
  CONSTRAINT bom_lines_usage_chk CHECK (usage IN
    ('DESIGN', 'MANUFACTURING', 'SERVICE', 'SPARE', 'REFERENCE')),
  CONSTRAINT bom_lines_status_chk CHECK (line_status IN
    ('draft', 'active', 'inactive', 'obsolete')),
  CONSTRAINT bom_lines_version_chk CHECK (version >= 1)
);
CREATE UNIQUE INDEX IF NOT EXISTS bom_lines_identity_uniq
  ON ai.bom_lines (tenant_id, bom_header_id, line_key)
  WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS bom_lines_parent_idx
  ON ai.bom_lines (tenant_id, bom_header_id, parent_revision_id, sequence)
  WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS bom_lines_child_idx
  ON ai.bom_lines (tenant_id, child_item_id)
  WHERE deleted_at IS NULL;

-- --- EBOM -> MBOM transformation (proposal only) -------------------------
-- A run records what was proposed. It never writes to ai.bom_lines; promotion
-- is a separate, audited service action.
CREATE TABLE IF NOT EXISTS ai.bom_transformation_runs (
  id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  source_header_id  bigint      NOT NULL REFERENCES ai.bom_headers(id) ON DELETE CASCADE,
  target_header_id  bigint      REFERENCES ai.bom_headers(id) ON DELETE SET NULL,
  mode              text        NOT NULL DEFAULT 'DRY_RUN',
  status            text        NOT NULL DEFAULT 'completed',
  summary           jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_by        text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  deleted_at        timestamptz,
  CONSTRAINT bom_transformation_runs_mode_chk CHECK (mode IN ('DRY_RUN', 'EXECUTE')),
  CONSTRAINT bom_transformation_runs_status_chk CHECK (status IN
    ('pending', 'running', 'completed', 'failed'))
);
CREATE INDEX IF NOT EXISTS bom_transformation_runs_source_idx
  ON ai.bom_transformation_runs (tenant_id, source_header_id, created_at DESC)
  WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS ai.bom_transformation_entries (
  id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  run_id            bigint      NOT NULL REFERENCES ai.bom_transformation_runs(id) ON DELETE CASCADE,
  source_line_id    bigint      REFERENCES ai.bom_lines(id) ON DELETE SET NULL,
  target_line_id    bigint      REFERENCES ai.bom_lines(id) ON DELETE SET NULL,
  mapping_type      text        NOT NULL DEFAULT 'UNMATCHED',
  quantity          numeric(20,6),
  unit_of_measure   text,
  notes             text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bom_transformation_entries_mapping_chk CHECK (mapping_type IN
    ('ONE_TO_ONE', 'ONE_TO_MANY', 'MANY_TO_ONE', 'UNMATCHED', 'CONSTANT'))
);
CREATE INDEX IF NOT EXISTS bom_transformation_entries_run_idx
  ON ai.bom_transformation_entries (tenant_id, run_id);

-- --- Reconciliation history ---------------------------------------------
CREATE TABLE IF NOT EXISTS ai.bom_reconciliations (
  id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  source_header_id  bigint      NOT NULL REFERENCES ai.bom_headers(id) ON DELETE CASCADE,
  target_header_id  bigint      REFERENCES ai.bom_headers(id) ON DELETE SET NULL,
  run_id            bigint      REFERENCES ai.bom_transformation_runs(id) ON DELETE SET NULL,
  status            text        NOT NULL DEFAULT 'open',
  exceptions        jsonb       NOT NULL DEFAULT '[]'::jsonb,
  summary           jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_by        text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  deleted_at        timestamptz,
  CONSTRAINT bom_reconciliations_status_chk CHECK (status IN
    ('open', 'matched', 'exceptions', 'resolved'))
);
CREATE INDEX IF NOT EXISTS bom_reconciliations_source_idx
  ON ai.bom_reconciliations (tenant_id, source_header_id, created_at DESC)
  WHERE deleted_at IS NULL;

-- --- updated_at triggers ------------------------------------------------
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'product_items', 'product_revisions', 'bom_headers', 'bom_lines',
    'bom_transformation_runs', 'bom_reconciliations'
  ] LOOP
    EXECUTE format(
      'DROP TRIGGER IF EXISTS trg_%I_updated_at ON ai.%I', tbl, tbl
    );
    EXECUTE format(
      'CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON ai.%I '
      'FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at()', tbl, tbl
    );
  END LOOP;
END
$$;

-- --- RLS: direct tenant ownership ---------------------------------------
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'product_items', 'product_revisions', 'bom_headers', 'bom_lines',
    'bom_transformation_runs', 'bom_transformation_entries',
    'bom_reconciliations'
  ] LOOP
    EXECUTE format('ALTER TABLE ai.%I ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE ai.%I FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON ai.%I', tbl);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON ai.%I FOR ALL TO PUBLIC '
      'USING (ai.tenant_isolation_allows(tenant_id)) '
      'WITH CHECK (ai.tenant_isolation_allows(tenant_id))',
      tbl
    );
  END LOOP;
END
$$;

-- --- Integrity: no cross-tenant references ------------------------------
DO $$
DECLARE
  spec record;
  mismatch bigint;
BEGIN
  FOR spec IN
    SELECT * FROM (VALUES
      ('product_revisions', 'item_id', 'product_items', 'id'),
      ('bom_headers', 'root_item_id', 'product_items', 'id'),
      ('bom_headers', 'root_revision_id', 'product_revisions', 'id'),
      ('bom_lines', 'bom_header_id', 'bom_headers', 'id'),
      ('bom_lines', 'parent_revision_id', 'product_revisions', 'id'),
      ('bom_lines', 'child_item_id', 'product_items', 'id'),
      ('bom_lines', 'child_revision_id', 'product_revisions', 'id'),
      ('bom_transformation_runs', 'source_header_id', 'bom_headers', 'id'),
      ('bom_transformation_runs', 'target_header_id', 'bom_headers', 'id'),
      ('bom_transformation_entries', 'run_id', 'bom_transformation_runs', 'id'),
      ('bom_reconciliations', 'source_header_id', 'bom_headers', 'id'),
      ('bom_reconciliations', 'target_header_id', 'bom_headers', 'id'),
      ('bom_reconciliations', 'run_id', 'bom_transformation_runs', 'id')
    ) AS v(child, child_col, parent, parent_col)
  LOOP
    EXECUTE format(
      'SELECT count(*) FROM ai.%I c JOIN ai.%I p ON p.%I = c.%I '
      'WHERE c.%I IS NOT NULL AND c.tenant_id <> p.tenant_id',
      spec.child, spec.parent, spec.parent_col, spec.child_col, spec.child_col
    ) INTO mismatch;
    IF mismatch > 0 THEN
      RAISE EXCEPTION
        'cross-tenant reference detected: %.% references another tenant (% rows)',
        spec.child, spec.child_col, mismatch;
    END IF;
  END LOOP;
END
$$;

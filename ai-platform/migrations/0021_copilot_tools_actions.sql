-- 0021_copilot_tools_actions.sql — Stage 5 Copilot: tool trace + controlled actions.
--
-- Additive. No existing conversation, message, citation, agent or approval table
-- is modified. Tenant scoping is enforced by the direct tenant_id column, which
-- migration 0018's RLS loop covers automatically (ENABLE + FORCE + one policy).
--
-- Guarantees encoded here:
--   * Tool invocations are an audit trace of *read-only* tool calls bound to the
--     assistant message that used them. They store identifiers, timing and
--     bounded argument/result summaries — never full enterprise payloads.
--   * Controlled actions are separated from execution. A proposed action is
--     inert; approving it does not execute it. The exact operation is bound by
--     `operation_hash`, which is unique per tenant, so a replayed or duplicated
--     proposal/execution cannot take effect twice.
--   * Requested/approved/executed identities are recorded independently.

CREATE TABLE IF NOT EXISTS ai.copilot_tool_invocations (
  id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  conversation_id bigint
    REFERENCES ai.assistant_conversations(id) ON DELETE CASCADE,
  message_id      bigint
    REFERENCES ai.assistant_messages(id) ON DELETE CASCADE,
  tool_code       text        NOT NULL,
  status          text        NOT NULL DEFAULT 'succeeded',
  read_only       boolean     NOT NULL DEFAULT true,
  arguments       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  result_summary  jsonb       NOT NULL DEFAULT '{}'::jsonb,
  error_class     text,
  duration_ms     integer,
  request_id      text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT copilot_tool_invocations_status_chk CHECK (status IN
    ('succeeded', 'failed', 'denied', 'timeout'))
);
CREATE INDEX IF NOT EXISTS copilot_tool_invocations_message_idx
  ON ai.copilot_tool_invocations (tenant_id, message_id);
CREATE INDEX IF NOT EXISTS copilot_tool_invocations_conversation_idx
  ON ai.copilot_tool_invocations (tenant_id, conversation_id, created_at DESC);

CREATE TABLE IF NOT EXISTS ai.copilot_actions (
  id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  conversation_id   bigint
    REFERENCES ai.assistant_conversations(id) ON DELETE SET NULL,
  message_id        bigint
    REFERENCES ai.assistant_messages(id) ON DELETE SET NULL,
  action_type       text        NOT NULL,
  target            text,
  summary           text        NOT NULL,
  arguments         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  expected_effect   text,
  evidence          jsonb       NOT NULL DEFAULT '[]'::jsonb,
  operation_hash    text        NOT NULL,
  risk_class        text        NOT NULL DEFAULT 'controlled_mutation',
  status            text        NOT NULL DEFAULT 'proposed',
  requested_by      bigint,
  requested_by_name text,
  approved_by       bigint,
  approved_by_name  text,
  decision_reason   text,
  decided_at        timestamptz,
  executed_by       bigint,
  executed_by_name  text,
  executed_at       timestamptz,
  result            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  error_class       text,
  request_id        text,
  expires_at        timestamptz,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT copilot_actions_status_chk CHECK (status IN
    ('proposed', 'approved', 'rejected', 'expired', 'executed', 'failed')),
  CONSTRAINT copilot_actions_hash_uniq UNIQUE (tenant_id, operation_hash)
);
CREATE INDEX IF NOT EXISTS copilot_actions_inbox_idx
  ON ai.copilot_actions (tenant_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS copilot_actions_conversation_idx
  ON ai.copilot_actions (tenant_id, conversation_id, created_at DESC);

DROP TRIGGER IF EXISTS trg_copilot_actions_updated_at ON ai.copilot_actions;
CREATE TRIGGER trg_copilot_actions_updated_at
  BEFORE UPDATE ON ai.copilot_actions
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

-- RLS: both tables carry tenant_id directly, so the 0018 loop covers them on a
-- fresh install. Apply the same policy here as well so an upgraded database
-- gets the policy without re-running 0018.
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY['copilot_tool_invocations', 'copilot_actions'] LOOP
    EXECUTE format('ALTER TABLE ai.%I ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE ai.%I FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON ai.%I', tbl);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON ai.%I FOR ALL TO PUBLIC '
      'USING (ai.tenant_isolation_allows(tenant_id)) '
      'WITH CHECK (ai.tenant_isolation_allows(tenant_id))',
      tbl
    );
  END LOOP;
END
$$;

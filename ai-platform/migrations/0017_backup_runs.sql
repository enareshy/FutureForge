-- 0017_backup_runs.sql — SEC-20: operational backup and restore-drill records.
--
-- The backup tool writes one row per attempt. Rows contain metadata only:
-- no credentials, object keys, tenant identifiers, document content or paths.
-- Metrics are derived from the latest rows, so the records must remain
-- low-cardinality and safe to expose to operators.

CREATE TABLE IF NOT EXISTS ai.backup_runs (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id             text        NOT NULL UNIQUE,
  kind               text        NOT NULL,
  status             text        NOT NULL,
  started_at         timestamptz NOT NULL,
  finished_at        timestamptz,
  artifact_id        text,
  artifact_size_bytes bigint,
  duration_seconds   double precision,
  checksum           text,
  encrypted          boolean,
  integrity_ok       boolean,
  details            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  error_code         text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT backup_runs_kind_chk
    CHECK (kind IN ('backup', 'restore_drill')),
  CONSTRAINT backup_runs_status_chk
    CHECK (status IN ('running', 'succeeded', 'failed')),
  CONSTRAINT backup_runs_size_chk
    CHECK (artifact_size_bytes IS NULL OR artifact_size_bytes >= 0),
  CONSTRAINT backup_runs_duration_chk
    CHECK (duration_seconds IS NULL OR duration_seconds >= 0)
);

CREATE INDEX IF NOT EXISTS backup_runs_kind_started_idx
  ON ai.backup_runs (kind, started_at DESC);
CREATE INDEX IF NOT EXISTS backup_runs_status_finished_idx
  ON ai.backup_runs (status, finished_at DESC);

COMMENT ON TABLE ai.backup_runs IS
  'Backup and restore-drill outcomes (metadata only; no secrets or object keys).';

-- 0003_ai_knowledge.sql — knowledge sources, documents, chunks and pgvector embeddings.
--
-- Forward-only. Applied in a single transaction by scripts/migrate.sh.
--
-- Embedding dimensions are fixed at 1536 (text-embedding-3-small class models).
-- pgvector requires a fixed dimension for a vector column and for an ANN index,
-- so changing the embedding model dimension is a deliberate migration, not a
-- runtime option. The `dimensions` column preserves per-row metadata and a CHECK
-- constraint keeps it consistent with the column type.
--
-- Authorization note: similarity is NEVER authorization. Every row carries
-- tenant scoping and access-control metadata (classification, acl) that the
-- application must apply *before* returning or using retrieval results.

-- Knowledge source registry (files, URLs, object-store prefixes, manual entries).
CREATE TABLE IF NOT EXISTS ai.knowledge_sources (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint      NOT NULL,
  code           text        NOT NULL,
  name           text        NOT NULL,
  kind           text        NOT NULL DEFAULT 'file',
  uri            text,
  classification text        NOT NULL DEFAULT 'internal',
  acl            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  status         text        NOT NULL DEFAULT 'registered',
  config         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT knowledge_sources_uniq UNIQUE (tenant_id, code),
  CONSTRAINT knowledge_sources_kind_chk CHECK (kind IN ('file', 'url', 'object', 'manual')),
  CONSTRAINT knowledge_sources_status_chk
    CHECK (status IN ('registered', 'indexing', 'ready', 'failed', 'disabled'))
);
CREATE INDEX IF NOT EXISTS knowledge_sources_tenant_idx ON ai.knowledge_sources (tenant_id);

-- Documents. Large binaries live in object storage; only pointers are stored here.
-- (source_id, external_id) is the natural key that makes re-indexing idempotent.
CREATE TABLE IF NOT EXISTS ai.documents (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint      NOT NULL,
  source_id      bigint      NOT NULL REFERENCES ai.knowledge_sources(id) ON DELETE CASCADE,
  external_id    text        NOT NULL,
  title          text,
  mime_type      text,
  uri            text,
  object_key     text,
  checksum       text,
  size_bytes     bigint,
  classification text        NOT NULL DEFAULT 'internal',
  acl            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  metadata       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  status         text        NOT NULL DEFAULT 'pending',
  indexed_at     timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT documents_source_external_uniq UNIQUE (source_id, external_id),
  CONSTRAINT documents_status_chk
    CHECK (status IN ('pending', 'indexing', 'indexed', 'failed', 'stale'))
);
CREATE INDEX IF NOT EXISTS documents_tenant_idx ON ai.documents (tenant_id);
CREATE INDEX IF NOT EXISTS documents_source_idx ON ai.documents (source_id);
CREATE INDEX IF NOT EXISTS documents_status_idx ON ai.documents (status);

-- Chunks. Access-control metadata is stored with the indexed content so that
-- retrieval can be filtered without joining back to the source.
CREATE TABLE IF NOT EXISTS ai.document_chunks (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint      NOT NULL,
  document_id    bigint      NOT NULL REFERENCES ai.documents(id) ON DELETE CASCADE,
  chunk_index    integer     NOT NULL,
  content        text        NOT NULL,
  token_count    integer,
  checksum       text,
  classification text        NOT NULL DEFAULT 'internal',
  acl            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  metadata       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT document_chunks_uniq UNIQUE (document_id, chunk_index),
  CONSTRAINT document_chunks_index_chk CHECK (chunk_index >= 0)
);
CREATE INDEX IF NOT EXISTS document_chunks_tenant_idx ON ai.document_chunks (tenant_id);
CREATE INDEX IF NOT EXISTS document_chunks_document_idx ON ai.document_chunks (document_id);

-- Embeddings. Cosine distance is used (embedding models are L2-normalized);
-- the HNSW index is built for approximate nearest-neighbour search. Deleting a
-- chunk (or its document/source) cascades and removes stale embeddings.
CREATE TABLE IF NOT EXISTS ai.embeddings (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id  bigint      NOT NULL,
  chunk_id   bigint      NOT NULL REFERENCES ai.document_chunks(id) ON DELETE CASCADE,
  model_code text        NOT NULL,
  dimensions integer     NOT NULL DEFAULT 1536,
  embedding  vector(1536) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT embeddings_chunk_model_uniq UNIQUE (chunk_id, model_code),
  CONSTRAINT embeddings_dimensions_chk CHECK (dimensions = 1536)
);
CREATE INDEX IF NOT EXISTS embeddings_tenant_idx ON ai.embeddings (tenant_id);
CREATE INDEX IF NOT EXISTS embeddings_chunk_idx ON ai.embeddings (chunk_id);
CREATE INDEX IF NOT EXISTS embeddings_embedding_hnsw_idx
  ON ai.embeddings USING hnsw (embedding vector_cosine_ops);

-- updated_at maintenance
DROP TRIGGER IF EXISTS trg_knowledge_sources_updated_at ON ai.knowledge_sources;
CREATE TRIGGER trg_knowledge_sources_updated_at BEFORE UPDATE ON ai.knowledge_sources
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

DROP TRIGGER IF EXISTS trg_documents_updated_at ON ai.documents;
CREATE TRIGGER trg_documents_updated_at BEFORE UPDATE ON ai.documents
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

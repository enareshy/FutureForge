-- 0022_stage6_agent_platform_completion.sql — Stage 6 completion (Step 4).
--
-- Additive only. Extends the existing Stage 6 agent platform with the pieces
-- required for the enterprise agent lifecycle:
--
--   * agent lifecycle: suspended/active transitions, duplication provenance,
--     soft deletion, and a stored working configuration snapshot;
--   * reusable agent templates (tenant-scoped, instantiable, never executable
--     directly);
--   * execution-level working memory and optional persistent agent memory,
--     strictly tenant/agent/execution scoped and permission-aware;
--   * scheduling of agent executions (one-time and recurring) with a
--     claim-based duplicate-execution guard driven by scheduled_for;
--   * multi-agent delegation records (parent/child executions) with
--     loop-prevention metadata.
--
-- Tenant scoping: every new table carries an explicit tenant_id, so the 0018
-- RLS loop and this migration's own policy block cover them. Foreign keys never
-- cross tenants (enforced by the application, verified by the integrity block).
--
-- No existing Stage 1-6 table semantics are changed; only new nullable columns
-- are added to ai.agents and ai.executions.

-- --- Agent lifecycle completion -----------------------------------------
ALTER TABLE ai.agents
  ADD COLUMN IF NOT EXISTS duplicated_from_agent_id bigint
    REFERENCES ai.agents(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS suspended_at timestamptz,
  ADD COLUMN IF NOT EXISTS archived_at timestamptz,
  ADD COLUMN IF NOT EXISTS deleted_at timestamptz,
  ADD COLUMN IF NOT EXISTS working_config jsonb NOT NULL DEFAULT '{}'::jsonb;

ALTER TABLE ai.agents DROP CONSTRAINT IF EXISTS agents_lifecycle_chk;
ALTER TABLE ai.agents ADD CONSTRAINT agents_lifecycle_chk
  CHECK (lifecycle_status IN
    ('draft', 'active', 'inactive', 'suspended', 'published', 'deprecated',
     'disabled', 'archived'));

CREATE INDEX IF NOT EXISTS agents_deleted_idx
  ON ai.agents (tenant_id, deleted_at)
  WHERE deleted_at IS NOT NULL;

-- A soft-deleted agent must not be reusable; enforce it in the catalog query
-- through this partial helper index (kept narrow and maintenance-friendly).

-- --- Execution: working memory pointer + delegation ---------------------
ALTER TABLE ai.executions
  ADD COLUMN IF NOT EXISTS memory_scope text,
  ADD COLUMN IF NOT EXISTS delegation_depth integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS delegated_by_agent_id bigint
    REFERENCES ai.agents(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS executions_parent_idx
  ON ai.executions (tenant_id, parent_execution_id)
  WHERE parent_execution_id IS NOT NULL;

-- --- Reusable agent templates -------------------------------------------
CREATE TABLE IF NOT EXISTS ai.agent_templates (
  id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     bigint      NOT NULL,
  code          text        NOT NULL,
  name          text        NOT NULL,
  description   text,
  category      text,
  use_case      text,
  definition    jsonb       NOT NULL DEFAULT '{}'::jsonb,
  system_tools  jsonb       NOT NULL DEFAULT '[]'::jsonb,
  enabled       boolean     NOT NULL DEFAULT true,
  created_by    text,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_templates_code_uniq UNIQUE (tenant_id, code)
);
CREATE INDEX IF NOT EXISTS agent_templates_tenant_idx
  ON ai.agent_templates (tenant_id, enabled, category);

-- --- Agent memory --------------------------------------------------------
-- `scope` is one of: execution (working memory, bound to an execution),
-- conversation (bound to a conversation/session) or agent (persistent).
-- `expires_at` supports retention; readable memory is filtered by ownership
-- and by the caller's permissions in the service layer.
CREATE TABLE IF NOT EXISTS ai.agent_memory_entries (
  id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  agent_id        bigint      REFERENCES ai.agents(id) ON DELETE CASCADE,
  scope           text        NOT NULL DEFAULT 'agent',
  execution_id    bigint      REFERENCES ai.executions(id) ON DELETE CASCADE,
  conversation_id bigint,
  owner_actor_id  bigint,
  owner_username  text,
  memory_key      text        NOT NULL,
  content         text        NOT NULL,
  metadata        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  classification  text        NOT NULL DEFAULT 'internal',
  expires_at      timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_memory_scope_chk CHECK (scope IN
    ('execution', 'conversation', 'agent')),
  CONSTRAINT agent_memory_key_uniq
    UNIQUE (tenant_id, agent_id, scope, owner_actor_id, memory_key)
);
CREATE INDEX IF NOT EXISTS agent_memory_lookup_idx
  ON ai.agent_memory_entries (tenant_id, agent_id, scope, updated_at DESC);
CREATE INDEX IF NOT EXISTS agent_memory_expiry_idx
  ON ai.agent_memory_entries (tenant_id, expires_at)
  WHERE expires_at IS NOT NULL;

-- --- Agent schedules -----------------------------------------------------
-- `next_run_at` is the claim key. `last_run_key` records the exact scheduled
-- instant that produced an execution so a re-entrant poll cannot enqueue the
-- same instant twice; the unique partial index is the durable guard.
CREATE TABLE IF NOT EXISTS ai.agent_schedules (
  id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        bigint      NOT NULL,
  agent_id         bigint      NOT NULL REFERENCES ai.agents(id) ON DELETE CASCADE,
  name             text        NOT NULL,
  enabled          boolean     NOT NULL DEFAULT true,
  schedule_kind    text        NOT NULL DEFAULT 'once',
  cron             text,
  run_at           timestamptz,
  timezone         text        NOT NULL DEFAULT 'UTC',
  input            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  input_text       text,
  next_run_at      timestamptz,
  last_run_at      timestamptz,
  last_run_key     text,
  last_execution_id bigint     REFERENCES ai.executions(id) ON DELETE SET NULL,
  last_status      text,
  failure_count    integer     NOT NULL DEFAULT 0,
  created_by       text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_schedules_kind_chk CHECK (schedule_kind IN ('once', 'recurring')),
  CONSTRAINT agent_schedules_cron_chk CHECK (
    (schedule_kind = 'recurring' AND cron IS NOT NULL)
    OR (schedule_kind = 'once' AND run_at IS NOT NULL)
  )
);
CREATE INDEX IF NOT EXISTS agent_schedules_due_idx
  ON ai.agent_schedules (next_run_at)
  WHERE enabled AND next_run_at IS NOT NULL;

-- One execution per (schedule, scheduled instant). The key is stored on the
-- execution so a crash between insert and schedule update is idempotent.
ALTER TABLE ai.executions
  ADD COLUMN IF NOT EXISTS schedule_id bigint
    REFERENCES ai.agent_schedules(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS schedule_run_key text;
CREATE UNIQUE INDEX IF NOT EXISTS executions_schedule_run_uniq
  ON ai.executions (tenant_id, schedule_id, schedule_run_key)
  WHERE schedule_id IS NOT NULL AND schedule_run_key IS NOT NULL;

-- --- Delegation records --------------------------------------------------
CREATE TABLE IF NOT EXISTS ai.agent_delegations (
  id                 bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          bigint      NOT NULL,
  parent_execution_id bigint     NOT NULL
    REFERENCES ai.executions(id) ON DELETE CASCADE,
  child_execution_id bigint      REFERENCES ai.executions(id) ON DELETE SET NULL,
  parent_agent_id    bigint      REFERENCES ai.agents(id) ON DELETE SET NULL,
  child_agent_id     bigint      NOT NULL REFERENCES ai.agents(id) ON DELETE CASCADE,
  step_key           text        NOT NULL,
  mode               text        NOT NULL DEFAULT 'sequential',
  status             text        NOT NULL DEFAULT 'pending',
  depth              integer     NOT NULL DEFAULT 1,
  input_summary      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  result_summary     jsonb       NOT NULL DEFAULT '{}'::jsonb,
  error_class        text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_delegations_mode_chk CHECK (mode IN ('sequential', 'parallel')),
  CONSTRAINT agent_delegations_status_chk CHECK (status IN
    ('pending', 'running', 'completed', 'failed', 'cancelled', 'skipped')),
  CONSTRAINT agent_delegations_uniq UNIQUE (parent_execution_id, step_key)
);
CREATE INDEX IF NOT EXISTS agent_delegations_parent_idx
  ON ai.agent_delegations (tenant_id, parent_execution_id);
CREATE INDEX IF NOT EXISTS agent_delegations_child_idx
  ON ai.agent_delegations (tenant_id, child_execution_id);

-- --- updated_at triggers ------------------------------------------------

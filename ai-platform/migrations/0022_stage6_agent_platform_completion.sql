DROP TRIGGER IF EXISTS trg_agent_memory_updated_at ON ai.agent_memory_entries;
CREATE TRIGGER trg_agent_memory_updated_at
  BEFORE UPDATE ON ai.agent_memory_entries
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

DROP TRIGGER IF EXISTS trg_agent_schedules_updated_at ON ai.agent_schedules;
CREATE TRIGGER trg_agent_schedules_updated_at
  BEFORE UPDATE ON ai.agent_schedules
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

DROP TRIGGER IF EXISTS trg_agent_delegations_updated_at ON ai.agent_delegations;
CREATE TRIGGER trg_agent_delegations_updated_at
  BEFORE UPDATE ON ai.agent_delegations
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

-- --- RLS: direct tenant ownership ---------------------------------------
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'agent_templates', 'agent_memory_entries', 'agent_schedules',
    'agent_delegations'
  ] LOOP
    EXECUTE format('ALTER TABLE ai.%I ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE ai.%I FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON ai.%I', tbl);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON ai.%I FOR ALL TO PUBLIC '
      'USING (ai.tenant_isolation_allows(tenant_id)) '
      'WITH CHECK (ai.tenant_isolation_allows(tenant_id))',
      tbl
    );
  END LOOP;
END
$$;

-- --- Integrity: no cross-tenant references ------------------------------
DO $$
DECLARE
  spec record;
  mismatch bigint;
BEGIN
  FOR spec IN
    SELECT * FROM (VALUES
      ('agent_schedules', 'agent_id', 'agents', 'id'),
      ('agent_schedules', 'last_execution_id', 'executions', 'id'),
      ('agent_memory_entries', 'agent_id', 'agents', 'id'),
      ('agent_memory_entries', 'execution_id', 'executions', 'id'),
      ('agent_delegations', 'parent_execution_id', 'executions', 'id'),
      ('agent_delegations', 'child_execution_id', 'executions', 'id'),
      ('agent_delegations', 'parent_agent_id', 'agents', 'id'),
      ('agent_delegations', 'child_agent_id', 'agents', 'id'),
      ('executions', 'schedule_id', 'agent_schedules', 'id'),
      ('executions', 'delegated_by_agent_id', 'agents', 'id')
    ) AS v(child, child_col, parent, parent_col)
  LOOP
    EXECUTE format(
      'SELECT count(*) FROM ai.%I c JOIN ai.%I p ON p.%I = c.%I '
      'WHERE c.tenant_id <> p.tenant_id',
      spec.child, spec.parent, spec.parent_col, spec.child_col
    ) INTO mismatch;
    IF mismatch > 0 THEN
      RAISE EXCEPTION
        'cross-tenant reference detected: %.% references another tenant (% rows)',
        spec.child, spec.child_col, mismatch;
    END IF;
  END LOOP;
END
$$;

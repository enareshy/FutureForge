-- 0020_document_versions.sql — document version tracking + searchable metadata.
--
-- Stage: Enterprise Search and Knowledge Assistant (RC-2 Step 2).
--
-- Reuse note: documents already carry `metadata jsonb` and `updated_at`. This
-- migration does not introduce a second document store; it adds the minimum
-- needed to (a) expose a monotonic per-document version and (b) retain a
-- bounded history of superseded versions so an update/delete workflow can be
-- explained without keeping deleted content searchable.
--
-- Authorization note: version rows copy the document's tenant and inherit the
-- same RLS policy as every other tenant-owned table. History is *metadata only*
-- (title, checksum, size, classification, acl, metadata) — never chunk text —
-- so a version row can never resurrect content that was redacted or deleted.

ALTER TABLE ai.documents
  ADD COLUMN IF NOT EXISTS version bigint NOT NULL DEFAULT 1;

ALTER TABLE ai.documents
  DROP CONSTRAINT IF EXISTS documents_version_chk;
ALTER TABLE ai.documents
  ADD CONSTRAINT documents_version_chk CHECK (version >= 1);

-- Indexed metadata keys the enterprise search filters rely on. These are
-- expression indexes over the existing jsonb column rather than new columns, so
-- the document contract is unchanged and no backfill is required.
CREATE INDEX IF NOT EXISTS documents_metadata_product_idx
  ON ai.documents ((metadata -> 'product'))
  WHERE metadata ? 'product';

CREATE INDEX IF NOT EXISTS documents_metadata_part_number_idx
  ON ai.documents ((metadata -> 'part_number'))
  WHERE metadata ? 'part_number';

CREATE INDEX IF NOT EXISTS documents_metadata_revision_idx
  ON ai.documents ((metadata -> 'revision'))
  WHERE metadata ? 'revision';

-- Previous-version history. `document_id` is intentionally not a foreign key:
-- the row must survive a document purge so an operator can still explain what
-- was deleted and by which version. `source_id` is kept so history can be
-- listed per source without joining a deleted document.
CREATE TABLE IF NOT EXISTS ai.document_versions (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint      NOT NULL,
  document_id    bigint      NOT NULL,
  source_id      bigint      NOT NULL,
  external_id    text        NOT NULL,
  version        bigint      NOT NULL,
  title          text,
  mime_type      text,
  checksum       text,
  size_bytes     bigint,
  classification text        NOT NULL DEFAULT 'internal',
  acl            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  metadata       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  status         text        NOT NULL DEFAULT 'indexed',
  reason         text        NOT NULL DEFAULT 'superseded',
  superseded_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT document_versions_version_chk CHECK (version >= 1),
  CONSTRAINT document_versions_reason_chk
    CHECK (reason IN ('superseded', 'deleted', 'metadata_update')),
  CONSTRAINT document_versions_uniq UNIQUE (tenant_id, document_id, version)
);
CREATE INDEX IF NOT EXISTS document_versions_tenant_idx
  ON ai.document_versions (tenant_id, document_id, version DESC);
CREATE INDEX IF NOT EXISTS document_versions_source_idx
  ON ai.document_versions (tenant_id, source_id, superseded_at DESC);

-- Retention: keep the audit trail, not an unbounded copy. Anything older than
-- the newest 50 rows per document is pruned by the writer, not by a timer, so
-- this stays deterministic in tests and workers.

-- RLS: the new table owns a tenant_id directly, so it gets the same FORCE +
-- policy treatment as every other tenant-owned table in 0018. Applying it here
-- keeps the policy definition next to the table it protects.
ALTER TABLE ai.document_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai.document_versions FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON ai.document_versions;
CREATE POLICY tenant_isolation ON ai.document_versions FOR ALL TO PUBLIC
  USING (ai.tenant_isolation_allows(tenant_id))
  WITH CHECK (ai.tenant_isolation_allows(tenant_id));

COMMENT ON TABLE ai.document_versions IS
  'Metadata-only history of superseded/deleted document versions; never stores chunk text.';
COMMENT ON COLUMN ai.documents.version IS
  'Monotonic document version; incremented on content replacement and metadata updates.';

-- 0008_stage3_assistant.sql — Stage 3: assistant conversations, message source
-- references, indexing-job lifecycle fields, and chunk source location.
--
-- Forward-only. Applied in a single transaction by scripts/migrate.sh.
--
-- Reuse note: knowledge sources/documents/chunks/embeddings/jobs already exist
-- (0003/0004) and are reused as-is. This migration only *extends* them and adds
-- the conversation/message/message-source model that Stage 3 requires.
--
-- Authorization note: every conversation/message/source row is tenant- and
-- actor-scoped. Historical answers must never become a route to content the user
-- is no longer allowed to access, so retrieval permissions are re-validated on
-- every request (never trusted from stored history alone).

-- --- Assistant conversations -------------------------------------------
-- Soft-delete via `deleted_at` (and status='deleted') keeps retention/erasure
-- auditable; the message/source rows are removed by the FK cascade on hard delete.
CREATE TABLE IF NOT EXISTS ai.assistant_conversations (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id  bigint      NOT NULL,
  actor_id   bigint,
  title      text,
  status     text        NOT NULL DEFAULT 'active',
  metadata   jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT assistant_conversations_status_chk
    CHECK (status IN ('active', 'archived', 'deleted'))
);
CREATE INDEX IF NOT EXISTS assistant_conversations_owner_idx
  ON ai.assistant_conversations (tenant_id, actor_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS assistant_conversations_tenant_idx
  ON ai.assistant_conversations (tenant_id, updated_at DESC);

-- --- Assistant messages -------------------------------------------------
CREATE TABLE IF NOT EXISTS ai.assistant_messages (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint      NOT NULL,
  conversation_id bigint     NOT NULL
    REFERENCES ai.assistant_conversations(id) ON DELETE CASCADE,
  role           text        NOT NULL,
  content        text        NOT NULL DEFAULT '',
  answer_status  text,
  confidence     numeric(8, 6),
  is_mock        boolean,
  model_code     text,
  provider_code  text,
  token_usage    jsonb       NOT NULL DEFAULT '{}'::jsonb,
  latency_ms     integer,
  execution_id   bigint      REFERENCES ai.executions(id) ON DELETE SET NULL,
  request_id     uuid,
  error          jsonb,
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assistant_messages_role_chk
    CHECK (role IN ('user', 'assistant', 'system')),
  CONSTRAINT assistant_messages_answer_status_chk
    CHECK (answer_status IS NULL
           OR answer_status IN ('answered', 'insufficient_evidence', 'error'))
);
CREATE INDEX IF NOT EXISTS assistant_messages_conversation_idx
  ON ai.assistant_messages (conversation_id, created_at);
CREATE INDEX IF NOT EXISTS assistant_messages_tenant_idx
  ON ai.assistant_messages (tenant_id, conversation_id);

-- --- Verified source references for an assistant answer ----------------
-- Independent of live chunks: a citation is a *snapshot* (score/snippet/location)
-- so an audit can show what supported an answer even if the source is later
-- re-indexed or deleted. IDs are kept for deep-linking when still authorized.
CREATE TABLE IF NOT EXISTS ai.assistant_message_sources (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL,
  message_id  bigint      NOT NULL
    REFERENCES ai.assistant_messages(id) ON DELETE CASCADE,
  rank        integer     NOT NULL,
  source_id   bigint,
  document_id bigint,
  chunk_id    bigint,
  source_code text,
  chunk_index integer,
  page        integer,
  section     text,
  score       numeric(10, 6),
  snippet     text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assistant_message_sources_uniq UNIQUE (message_id, rank),
  CONSTRAINT assistant_message_sources_rank_chk CHECK (rank >= 1)
);
CREATE INDEX IF NOT EXISTS assistant_message_sources_message_idx
  ON ai.assistant_message_sources (message_id);

-- Link feedback to a specific assistant message (optional; execution link is
-- retained). Feedback remains tenant-scoped.
ALTER TABLE ai.feedback
  ADD COLUMN IF NOT EXISTS message_id bigint
    REFERENCES ai.assistant_messages(id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS feedback_message_idx ON ai.feedback (message_id);

-- --- Indexing job lifecycle (bounded retries, leases, classification) ---
-- `stage` is the human-readable pipeline stage for the UI; `error_class`
-- classifies failures (validation | provider | storage | timeout | internal) so
-- the UI can show safe summaries and retries can target eligible failures.
ALTER TABLE ai.jobs ADD COLUMN IF NOT EXISTS stage text;
ALTER TABLE ai.jobs ADD COLUMN IF NOT EXISTS max_attempts integer NOT NULL DEFAULT 5;
ALTER TABLE ai.jobs ADD COLUMN IF NOT EXISTS error_class text;
-- Lease prevents duplicate concurrent processing of the same job by two workers.
ALTER TABLE ai.jobs ADD COLUMN IF NOT EXISTS lease_expires_at timestamptz;

-- --- Chunk source location ---------------------------------------------
-- Page (PDF) and section (markdown heading / structural label) are preserved so
-- citations can resolve to a real location, not just a chunk index.
ALTER TABLE ai.document_chunks ADD COLUMN IF NOT EXISTS page integer;
ALTER TABLE ai.document_chunks ADD COLUMN IF NOT EXISTS section text;

-- --- Document upload / dedupe / search-sync metadata --------------------
-- `object_key` (original in object storage) already exists. Add a checksum
-- lookup index for duplicate detection and a marker for OpenSearch sync state.
CREATE INDEX IF NOT EXISTS documents_tenant_checksum_idx
  ON ai.documents (tenant_id, checksum);
ALTER TABLE ai.documents ADD COLUMN IF NOT EXISTS search_indexed_at timestamptz;
ALTER TABLE ai.documents ADD COLUMN IF NOT EXISTS error_class text;

-- updated_at maintenance
DROP TRIGGER IF EXISTS trg_assistant_conversations_updated_at
  ON ai.assistant_conversations;
CREATE TRIGGER trg_assistant_conversations_updated_at
  BEFORE UPDATE ON ai.assistant_conversations
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

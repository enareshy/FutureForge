-- 0007_ai_ml.sql — MLflow-backed experiment tracking and the classical-ML model registry.
--
-- Forward-only. Applied in a single transaction by scripts/migrate.sh.
--
-- Design notes:
--   * The `ai` schema remains the authorization-metadata authority: tenant
--     scoping and access control live here. MLflow (when configured) is an
--     optional external tracking/artifact backend; the platform records a
--     reference to it (external_* columns) but never depends on it being up.
--   * Classical ML models are kept separate from the LLM provider registry
--     (`ai.models`); LLM/provider configuration is not a trained artifact.
--   * `validation` records explicit, honest machine-learning validation facts
--     (e.g. synthetic data flag, held-out metrics). Nothing here asserts that a
--     model is production-useful for any manufacturing outcome.

-- Experiment definitions (one logical ML experiment per tenant).
CREATE TABLE IF NOT EXISTS ai.experiments (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id              bigint      NOT NULL,
  code                   text        NOT NULL,
  name                   text        NOT NULL,
  description            text,
  problem_type           text        NOT NULL DEFAULT 'classification',
  tracking_backend       text        NOT NULL DEFAULT 'local',
  external_experiment_id text,
  tags                   jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT experiments_uniq UNIQUE (tenant_id, code),
  CONSTRAINT experiments_problem_type_chk
    CHECK (problem_type IN ('classification', 'regression', 'ranking'))
);
CREATE INDEX IF NOT EXISTS experiments_tenant_idx ON ai.experiments (tenant_id);

-- A single training/evaluation run within an experiment, with a reproducible
-- configuration snapshot and an explicit dataset reference.
CREATE TABLE IF NOT EXISTS ai.experiment_runs (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  experiment_id     bigint      NOT NULL REFERENCES ai.experiments(id) ON DELETE CASCADE,
  run_uuid          uuid        NOT NULL DEFAULT gen_random_uuid(),
  run_name          text,
  status            text        NOT NULL DEFAULT 'running',
  external_run_id   text,
  artifact_uri      text,
  params            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  metrics           jsonb       NOT NULL DEFAULT '{}'::jsonb,
  training_config   jsonb       NOT NULL DEFAULT '{}'::jsonb,
  dataset_ref       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  code_version      text,
  logged_by         bigint,
  created_at        timestamptz NOT NULL DEFAULT now(),
  finished_at       timestamptz,
  CONSTRAINT experiment_runs_uuid_uniq UNIQUE (run_uuid),
  CONSTRAINT experiment_runs_status_chk
    CHECK (status IN ('running', 'finished', 'failed', 'killed'))
);
CREATE INDEX IF NOT EXISTS experiment_runs_experiment_idx
  ON ai.experiment_runs (experiment_id, created_at DESC);
CREATE INDEX IF NOT EXISTS experiment_runs_tenant_idx
  ON ai.experiment_runs (tenant_id, created_at DESC);

-- Registered classical-ML models (framework: scikit-learn / xgboost / ...).
CREATE TABLE IF NOT EXISTS ai.ml_models (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    bigint      NOT NULL,
  code         text        NOT NULL,
  name         text        NOT NULL,
  description  text,
  problem_type text        NOT NULL DEFAULT 'classification',
  framework    text        NOT NULL DEFAULT 'scikit-learn',
  task         text,
  stage        text        NOT NULL DEFAULT 'none',
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ml_models_uniq UNIQUE (tenant_id, code),
  CONSTRAINT ml_models_problem_type_chk
    CHECK (problem_type IN ('classification', 'regression', 'ranking')),
  CONSTRAINT ml_models_stage_chk
    CHECK (stage IN ('none', 'staging', 'production', 'archived'))
);
CREATE INDEX IF NOT EXISTS ml_models_tenant_idx ON ai.ml_models (tenant_id);

-- Immutable, monotonically versioned model artifacts tied to an experiment run.
CREATE TABLE IF NOT EXISTS ai.ml_model_versions (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ml_model_id            bigint      NOT NULL REFERENCES ai.ml_models(id) ON DELETE CASCADE,
  version                integer     NOT NULL,
  run_id                 bigint      REFERENCES ai.experiment_runs(id) ON DELETE SET NULL,
  status                 text        NOT NULL DEFAULT 'staging',
  framework              text,
  metrics                jsonb       NOT NULL DEFAULT '{}'::jsonb,
  parameters             jsonb       NOT NULL DEFAULT '{}'::jsonb,
  validation             jsonb       NOT NULL DEFAULT '{}'::jsonb,
  artifact_uri           text,
  external_model_version text,
  created_at             timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ml_model_versions_uniq UNIQUE (ml_model_id, version),
  CONSTRAINT ml_model_versions_status_chk
    CHECK (status IN ('staging', 'production', 'archived'))
);
CREATE INDEX IF NOT EXISTS ml_model_versions_model_idx
  ON ai.ml_model_versions (ml_model_id, version DESC);

-- Evaluation suite definitions and per-case results already exist (0004:
-- ai.evaluations / ai.evaluation_results) and are reused by Phase 11 as-is;
-- this migration adds only the experiment-tracking and model-registry tables.

-- updated_at maintenance
DROP TRIGGER IF EXISTS trg_experiments_updated_at ON ai.experiments;
CREATE TRIGGER trg_experiments_updated_at BEFORE UPDATE ON ai.experiments
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

DROP TRIGGER IF EXISTS trg_ml_models_updated_at ON ai.ml_models;
CREATE TRIGGER trg_ml_models_updated_at BEFORE UPDATE ON ai.ml_models
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

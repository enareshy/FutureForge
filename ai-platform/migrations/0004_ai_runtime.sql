-- 0004_ai_runtime.sql — executions, usage/cost, evaluations, feedback, audit, jobs.
--
-- Forward-only. Applied in a single transaction by scripts/migrate.sh.
--
-- `ai.audit_events` is a local mirror that references the enterprise audit
-- service; the enterprise audit trail remains authoritative.

-- Execution / request records. One row per AI operation (chat, embed, rag, agent).
CREATE TABLE IF NOT EXISTS ai.executions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    bigint      NOT NULL,
  request_id   uuid        NOT NULL DEFAULT gen_random_uuid(),
  actor_id     bigint,
  agent_id     bigint REFERENCES ai.agents(id) ON DELETE SET NULL,
  model_id     bigint REFERENCES ai.models(id) ON DELETE SET NULL,
  operation    text        NOT NULL,
  status       text        NOT NULL DEFAULT 'pending',
  input        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  output       jsonb,
  error        jsonb,
  latency_ms   integer,
  token_usage  jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at   timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  CONSTRAINT executions_request_id_uniq UNIQUE (request_id),
  CONSTRAINT executions_operation_chk CHECK (operation IN ('chat', 'embed', 'rag', 'agent')),
  CONSTRAINT executions_status_chk
    CHECK (status IN ('pending', 'running', 'succeeded', 'failed', 'cancelled'))
);
CREATE INDEX IF NOT EXISTS executions_tenant_created_idx ON ai.executions (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS executions_agent_idx ON ai.executions (agent_id);

-- Usage and cost metadata, one row per measured quantity.
CREATE TABLE IF NOT EXISTS ai.usage_records (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    bigint      NOT NULL,
  execution_id bigint REFERENCES ai.executions(id) ON DELETE CASCADE,
  provider_code text,
  model_code   text,
  kind         text        NOT NULL,
  quantity     bigint      NOT NULL DEFAULT 0,
  unit         text        NOT NULL DEFAULT 'tokens',
  unit_cost    numeric(18, 8),
  total_cost   numeric(18, 8),
  currency     text        NOT NULL DEFAULT 'USD',
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT usage_records_kind_chk CHECK (kind IN ('input', 'output', 'embedding', 'request'))
);
CREATE INDEX IF NOT EXISTS usage_records_tenant_created_idx ON ai.usage_records (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS usage_records_execution_idx ON ai.usage_records (execution_id);

-- Evaluation definitions and per-case results.
CREATE TABLE IF NOT EXISTS ai.evaluations (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id  bigint      NOT NULL,
  code       text        NOT NULL,
  name       text        NOT NULL,
  kind       text        NOT NULL DEFAULT 'retrieval',
  config     jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT evaluations_uniq UNIQUE (tenant_id, code),
  CONSTRAINT evaluations_kind_chk CHECK (kind IN ('retrieval', 'answer', 'safety'))
);

CREATE TABLE IF NOT EXISTS ai.evaluation_results (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evaluation_id bigint      NOT NULL REFERENCES ai.evaluations(id) ON DELETE CASCADE,
  case_id       text        NOT NULL,
  metrics       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  passed        boolean,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS evaluation_results_eval_idx ON ai.evaluation_results (evaluation_id);

-- User feedback on an execution.
CREATE TABLE IF NOT EXISTS ai.feedback (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    bigint      NOT NULL,
  execution_id bigint REFERENCES ai.executions(id) ON DELETE CASCADE,
  actor_id     bigint,
  rating       integer,
  comment      text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT feedback_rating_chk CHECK (rating IS NULL OR rating BETWEEN -1 AND 5)
);
CREATE INDEX IF NOT EXISTS feedback_tenant_idx ON ai.feedback (tenant_id);
CREATE INDEX IF NOT EXISTS feedback_execution_idx ON ai.feedback (execution_id);

-- Local audit mirror referencing the enterprise audit service.
CREATE TABLE IF NOT EXISTS ai.audit_events (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     bigint      NOT NULL,
  execution_id  bigint REFERENCES ai.executions(id) ON DELETE SET NULL,
  actor_id      bigint,
  action        text        NOT NULL,
  resource_type text,
  resource_id   text,
  outcome       text        NOT NULL DEFAULT 'success',
  request_id    uuid,
  detail        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT audit_events_outcome_chk CHECK (outcome IN ('success', 'failure', 'denied'))
);
CREATE INDEX IF NOT EXISTS audit_events_tenant_created_idx ON ai.audit_events (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS audit_events_resource_idx ON ai.audit_events (resource_type, resource_id);

-- Background job / indexing status.
CREATE TABLE IF NOT EXISTS ai.jobs (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  type            text        NOT NULL,
  status          text        NOT NULL DEFAULT 'queued',
  source_id       bigint REFERENCES ai.knowledge_sources(id) ON DELETE SET NULL,
  idempotency_key text,
  progress        numeric(5, 2) NOT NULL DEFAULT 0,
  attempts        integer     NOT NULL DEFAULT 0,
  payload         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  result          jsonb,
  error           jsonb,
  created_at      timestamptz NOT NULL DEFAULT now(),
  started_at      timestamptz,
  finished_at     timestamptz,
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT jobs_status_chk
    CHECK (status IN ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
  CONSTRAINT jobs_progress_chk CHECK (progress >= 0 AND progress <= 100),
  CONSTRAINT jobs_idempotency_uniq UNIQUE (tenant_id, idempotency_key)
);
CREATE INDEX IF NOT EXISTS jobs_tenant_status_idx ON ai.jobs (tenant_id, status);
CREATE INDEX IF NOT EXISTS jobs_source_idx ON ai.jobs (source_id);

-- updated_at maintenance
DROP TRIGGER IF EXISTS trg_jobs_updated_at ON ai.jobs;
CREATE TRIGGER trg_jobs_updated_at BEFORE UPDATE ON ai.jobs
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

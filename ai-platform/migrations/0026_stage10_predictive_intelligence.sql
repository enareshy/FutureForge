-- --- updated_at triggers ------------------------------------------------
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'predictive_feature_definitions', 'predictive_feature_values',
    'predictive_datasets', 'predictive_dataset_versions', 'predictive_models',
    'predictive_model_versions', 'predictive_predictions',
    'predictive_recommendations', 'predictive_schedules'
  ] LOOP
    EXECUTE format(
      'DROP TRIGGER IF EXISTS trg_%I_updated_at ON ai.%I', tbl, tbl
    );
    EXECUTE format(
      'CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON ai.%I '
      'FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at()', tbl, tbl
    );
  END LOOP;
END
$$;

-- --- RLS: direct tenant ownership ---------------------------------------
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'predictive_feature_definitions', 'predictive_feature_values',
    'predictive_datasets', 'predictive_dataset_versions', 'predictive_models',
    'predictive_model_versions', 'predictive_predictions',
    'predictive_recommendations', 'predictive_recommendation_feedback',
    'predictive_schedules'
  ] LOOP
    EXECUTE format('ALTER TABLE ai.%I ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE ai.%I FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON ai.%I', tbl);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON ai.%I FOR ALL TO PUBLIC '
      'USING (ai.tenant_isolation_allows(tenant_id)) '
      'WITH CHECK (ai.tenant_isolation_allows(tenant_id))',
      tbl
    );
  END LOOP;
END
$$;

-- --- Integrity: no cross-tenant references ------------------------------
DO $$
DECLARE
  spec record;
  mismatch bigint;
BEGIN
  FOR spec IN
    SELECT * FROM (VALUES
      ('predictive_dataset_versions', 'dataset_id', 'predictive_datasets', 'id'),
      ('predictive_model_versions', 'model_id', 'predictive_models', 'id'),
      ('predictive_model_versions', 'dataset_version_id',
       'predictive_dataset_versions', 'id'),
      ('predictive_recommendations', 'prediction_id', 'predictive_predictions', 'id'),
      ('predictive_recommendation_feedback', 'recommendation_id',
       'predictive_recommendations', 'id')
    ) AS v(child, child_col, parent, parent_col)
  LOOP
    EXECUTE format(
      'SELECT count(*) FROM ai.%I c JOIN ai.%I p ON p.%I = c.%I '
      'WHERE c.%I IS NOT NULL AND c.tenant_id <> p.tenant_id',
      spec.child, spec.parent, spec.parent_col, spec.child_col, spec.child_col
    ) INTO mismatch;
    IF mismatch > 0 THEN
      RAISE EXCEPTION
        'cross-tenant reference detected: %.% references another tenant (% rows)',
        spec.child, spec.child_col, mismatch;
    END IF;
  END LOOP;
END
$$;

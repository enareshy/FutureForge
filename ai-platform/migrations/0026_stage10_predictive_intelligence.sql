-- 0026_stage10_predictive_intelligence.sql — Predictive Intelligence (Step 8).
--
-- Additive only. Adds tenant-scoped predictive-intelligence foundation tables:
--   * feature definitions and observed feature values (with lineage/freshness)
--   * datasets and versioned train/evaluation splits
--   * a lightweight predictive strategy/model registry with versions
--   * predictions (rule-based, statistical, ML or insufficient-data results)
--   * recommendations and their review/feedback lifecycle
--   * prediction schedules reusing the existing worker/job cadence
--
-- These are *domain* records. Each prediction/recommendation may carry a
-- `graph_entity_id` pointing at the graph entity that represents it so the
-- digital thread and traversal keep working without a second graph model. The
-- batch ML experiment/model registry (ai.ml_models) is a different concern
-- (training runs); this registry versions the *prediction strategy* that
-- produced a result and is never presented as a validated ML model unless an
-- evaluation dataset version backs it.
--
-- Identity:
--   * predictive_feature_definitions  UNIQUE (tenant_id, feature_key)
--   * predictive_feature_values       UNIQUE (tenant_id, feature_key, entity_type, entity_id)
--   * predictive_datasets             UNIQUE (tenant_id, dataset_key)
--   * predictive_dataset_versions     UNIQUE (tenant_id, dataset_id, version, split)
--   * predictive_models               UNIQUE (tenant_id, model_key)
--   * predictive_model_versions       UNIQUE (tenant_id, model_id, version)
--   * predictive_predictions          UNIQUE (tenant_id, prediction_key)
--   * predictive_recommendations      UNIQUE (tenant_id, recommendation_key)
--   * predictive_schedules            UNIQUE (tenant_id, schedule_key)
--
-- RLS: every table carries an explicit tenant_id and reuses the same FORCE ROW
-- LEVEL SECURITY tenant_isolation policy as the rest of the `ai` schema.

-- --- Feature definitions -------------------------------------------------
CREATE TABLE IF NOT EXISTS ai.predictive_feature_definitions (
  id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id           bigint      NOT NULL,
  feature_key         text        NOT NULL,
  name                text,
  description         text,
  entity_type         text        NOT NULL DEFAULT 'any',
  data_type           text        NOT NULL DEFAULT 'number',
  source_system       text,
  extraction_spec     jsonb       NOT NULL DEFAULT '{}'::jsonb,
  freshness_ttl_hours integer     NOT NULL DEFAULT 168,
  lifecycle_status    text        NOT NULL DEFAULT 'active',
  attributes          jsonb       NOT NULL DEFAULT '{}'::jsonb,
  classification      text        NOT NULL DEFAULT 'internal',
  acl                 jsonb       NOT NULL DEFAULT '{}'::jsonb,
  version             integer     NOT NULL DEFAULT 1,
  created_by          text,
  updated_by          text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  deleted_at          timestamptz,
  CONSTRAINT predictive_feature_definitions_identity_uniq
    UNIQUE (tenant_id, feature_key),
  CONSTRAINT predictive_feature_definitions_data_type_chk CHECK (data_type IN
    ('number', 'boolean', 'string', 'json')),
  CONSTRAINT predictive_feature_definitions_lifecycle_chk CHECK (lifecycle_status IN
    ('active', 'deprecated', 'archived')),
  CONSTRAINT predictive_feature_definitions_ttl_chk CHECK (freshness_ttl_hours >= 1),
  CONSTRAINT predictive_feature_definitions_version_chk CHECK (version >= 1)
);
CREATE INDEX IF NOT EXISTS predictive_feature_definitions_lookup_idx
  ON ai.predictive_feature_definitions (tenant_id, entity_type, lifecycle_status)
  WHERE deleted_at IS NULL;


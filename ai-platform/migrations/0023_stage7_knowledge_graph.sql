-- 0023_stage7_knowledge_graph.sql — Enterprise Knowledge Graph & Digital Thread.
--
-- Additive only. Builds the graph foundation on PostgreSQL (no external graph
-- database): a tenant-scoped entity/relationship store with type registries,
-- provenance, confidence, effective dates, lifecycle status and lightweight
-- version history.
--
-- Identity: an entity is de-duplicated by
--   (tenant_id, entity_type, stable_key)
-- where `stable_key` is the caller/source supplied stable identity (for example
-- a normalised part number or a source-system object id). Re-ingesting the same
-- enterprise object therefore updates in place instead of creating duplicates.
--
-- Active relationships are unique per
--   (tenant_id, relationship_type, source_entity_id, target_entity_id)
-- for non-deleted rows; stale/inactive rows are retained for provenance but do
-- not block re-creation.
--
-- RLS: every table carries an explicit tenant_id and is covered by the same
-- FORCE ROW LEVEL SECURITY policy used by the rest of the ai schema. Graph rows
-- never grant access to the underlying enterprise records they describe.

-- --- Entity type registry -----------------------------------------------
-- Tenant-scoped so a deployment can extend the built-in catalog. Services seed
-- the built-in types in code and treat these rows as tenant overrides.
CREATE TABLE IF NOT EXISTS ai.graph_entity_types (
  id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  code            text        NOT NULL,
  name            text        NOT NULL,
  description     text,
  category        text,
  property_schema jsonb       NOT NULL DEFAULT '{}'::jsonb,
  enabled         boolean     NOT NULL DEFAULT true,
  created_by      text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT graph_entity_types_code_uniq UNIQUE (tenant_id, code)
);
CREATE INDEX IF NOT EXISTS graph_entity_types_tenant_idx
  ON ai.graph_entity_types (tenant_id, enabled, category);

-- --- Relationship type registry -----------------------------------------
-- `source_types`/`target_types` are JSON arrays of entity type codes; an empty
-- array means "any type". Validation runs in the service layer so behaviour is
-- identical for in-memory and PostgreSQL deployments.
CREATE TABLE IF NOT EXISTS ai.graph_relationship_types (
  id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  code            text        NOT NULL,
  name            text        NOT NULL,
  description     text,
  source_types    jsonb       NOT NULL DEFAULT '[]'::jsonb,
  target_types    jsonb       NOT NULL DEFAULT '[]'::jsonb,
  directed        boolean     NOT NULL DEFAULT true,
  property_schema jsonb       NOT NULL DEFAULT '{}'::jsonb,
  enabled         boolean     NOT NULL DEFAULT true,
  created_by      text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT graph_relationship_types_code_uniq UNIQUE (tenant_id, code)
);
CREATE INDEX IF NOT EXISTS graph_relationship_types_tenant_idx
  ON ai.graph_relationship_types (tenant_id, enabled);

-- --- Graph entities ------------------------------------------------------
CREATE TABLE IF NOT EXISTS ai.graph_entities (
  id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  entity_type       text        NOT NULL,
  stable_key        text        NOT NULL,
  external_id       text,
  source_system     text,
  source_ref        text,
  name              text,
  description       text,
  classification    text        NOT NULL DEFAULT 'internal',
  acl               jsonb       NOT NULL DEFAULT '{}'::jsonb,
  lifecycle_status  text        NOT NULL DEFAULT 'active',
  confidence        numeric(4,3) NOT NULL DEFAULT 1.000,
  properties        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  metadata          jsonb       NOT NULL DEFAULT '{}'::jsonb,
  valid_from        timestamptz,
  valid_to          timestamptz,
  version           integer     NOT NULL DEFAULT 1,
  created_by        text,
  updated_by        text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  deleted_at        timestamptz,
  CONSTRAINT graph_entities_stable_uniq UNIQUE (tenant_id, entity_type, stable_key),
  CONSTRAINT graph_entities_confidence_chk CHECK (confidence >= 0 AND confidence <= 1),
  CONSTRAINT graph_entities_version_chk CHECK (version >= 1),
  CONSTRAINT graph_entities_lifecycle_chk CHECK (lifecycle_status IN
    ('active', 'inactive', 'draft', 'released', 'obsolete', 'stale', 'archived'))
);
CREATE INDEX IF NOT EXISTS graph_entities_lookup_idx
  ON ai.graph_entities (tenant_id, entity_type, lifecycle_status)
  WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS graph_entities_external_idx
  ON ai.graph_entities (tenant_id, source_system, external_id)
  WHERE external_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS graph_entities_name_idx
  ON ai.graph_entities (tenant_id, lower(name))
  WHERE name IS NOT NULL;

-- --- Entity version history ---------------------------------------------
-- Metadata snapshot only. Kept append-only for provenance/audit; never used to
-- serve authorization decisions (the live row is always authoritative).
CREATE TABLE IF NOT EXISTS ai.graph_entity_versions (
  id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     bigint      NOT NULL,
  entity_id     bigint      NOT NULL REFERENCES ai.graph_entities(id) ON DELETE CASCADE,
  version       integer     NOT NULL,
  snapshot      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  change_reason text,
  created_by    text,
  created_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT graph_entity_versions_uniq UNIQUE (tenant_id, entity_id, version)
);
CREATE INDEX IF NOT EXISTS graph_entity_versions_entity_idx
  ON ai.graph_entity_versions (tenant_id, entity_id, version DESC);

-- --- Graph relationships -------------------------------------------------
CREATE TABLE IF NOT EXISTS ai.graph_relationships (
  id                 bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          bigint      NOT NULL,
  relationship_type  text        NOT NULL,
  source_entity_id   bigint      NOT NULL REFERENCES ai.graph_entities(id) ON DELETE CASCADE,
  target_entity_id   bigint      NOT NULL REFERENCES ai.graph_entities(id) ON DELETE CASCADE,
  properties         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  confidence         numeric(4,3) NOT NULL DEFAULT 1.000,
  source_system      text,
  source_ref         text,
  lifecycle_status   text        NOT NULL DEFAULT 'active',
  valid_from         timestamptz,
  valid_to           timestamptz,
  version            integer     NOT NULL DEFAULT 1,
  created_by         text,
  updated_by         text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  deleted_at         timestamptz,
  CONSTRAINT graph_relationships_no_self_chk CHECK (source_entity_id <> target_entity_id),
  CONSTRAINT graph_relationships_confidence_chk CHECK (confidence >= 0 AND confidence <= 1),
  CONSTRAINT graph_relationships_version_chk CHECK (version >= 1),
  CONSTRAINT graph_relationships_lifecycle_chk CHECK (lifecycle_status IN
    ('active', 'inactive', 'stale', 'archived'))
);
CREATE UNIQUE INDEX IF NOT EXISTS graph_relationships_active_uniq
  ON ai.graph_relationships
    (tenant_id, relationship_type, source_entity_id, target_entity_id)
  WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS graph_relationships_source_idx
  ON ai.graph_relationships (tenant_id, source_entity_id, relationship_type)
  WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS graph_relationships_target_idx
  ON ai.graph_relationships (tenant_id, target_entity_id, relationship_type)
  WHERE deleted_at IS NULL;

-- --- Relationship version history ---------------------------------------
CREATE TABLE IF NOT EXISTS ai.graph_relationship_versions (
  id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  relationship_id bigint      NOT NULL REFERENCES ai.graph_relationships(id) ON DELETE CASCADE,
  version         integer     NOT NULL,
  snapshot        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  change_reason   text,
  created_by      text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT graph_relationship_versions_uniq UNIQUE (tenant_id, relationship_id, version)
);
CREATE INDEX IF NOT EXISTS graph_relationship_versions_rel_idx
  ON ai.graph_relationship_versions (tenant_id, relationship_id, version DESC);

-- --- updated_at triggers ------------------------------------------------
DROP TRIGGER IF EXISTS trg_graph_entity_types_updated_at ON ai.graph_entity_types;
CREATE TRIGGER trg_graph_entity_types_updated_at
  BEFORE UPDATE ON ai.graph_entity_types
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

DROP TRIGGER IF EXISTS trg_graph_relationship_types_updated_at
  ON ai.graph_relationship_types;
CREATE TRIGGER trg_graph_relationship_types_updated_at
  BEFORE UPDATE ON ai.graph_relationship_types
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

DROP TRIGGER IF EXISTS trg_graph_entities_updated_at ON ai.graph_entities;
CREATE TRIGGER trg_graph_entities_updated_at
  BEFORE UPDATE ON ai.graph_entities
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

DROP TRIGGER IF EXISTS trg_graph_relationships_updated_at ON ai.graph_relationships;
CREATE TRIGGER trg_graph_relationships_updated_at
  BEFORE UPDATE ON ai.graph_relationships
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

-- --- RLS: direct tenant ownership ---------------------------------------
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'graph_entity_types', 'graph_relationship_types', 'graph_entities',
    'graph_entity_versions', 'graph_relationships', 'graph_relationship_versions'
  ] LOOP
    EXECUTE format('ALTER TABLE ai.%I ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE ai.%I FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON ai.%I', tbl);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON ai.%I FOR ALL TO PUBLIC '
      'USING (ai.tenant_isolation_allows(tenant_id)) '
      'WITH CHECK (ai.tenant_isolation_allows(tenant_id))',
      tbl
    );
  END LOOP;
END
$$;

-- --- Integrity: no cross-tenant references ------------------------------
DO $$
DECLARE
  spec record;
  mismatch bigint;
BEGIN
  FOR spec IN
    SELECT * FROM (VALUES
      ('graph_entity_versions', 'entity_id', 'graph_entities', 'id'),
      ('graph_relationships', 'source_entity_id', 'graph_entities', 'id'),
      ('graph_relationships', 'target_entity_id', 'graph_entities', 'id'),
      ('graph_relationship_versions', 'relationship_id', 'graph_relationships', 'id')
    ) AS v(child, child_col, parent, parent_col)
  LOOP
    EXECUTE format(
      'SELECT count(*) FROM ai.%I c JOIN ai.%I p ON p.%I = c.%I '
      'WHERE c.tenant_id <> p.tenant_id',
      spec.child, spec.parent, spec.parent_col, spec.child_col
    ) INTO mismatch;
    IF mismatch > 0 THEN
      RAISE EXCEPTION
        'cross-tenant reference detected: %.% references another tenant (% rows)',
        spec.child, spec.child_col, mismatch;
    END IF;
  END LOOP;
END
$$;

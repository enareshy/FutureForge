-- 0002_ai_config.sql — AI platform configuration, provider/model registry, prompts, agents.
--
-- Forward-only. Applied in a single transaction by scripts/migrate.sh.
-- Tenant scoping: `tenant_id` aligns with the enterprise organizations.id
-- (bigint). It is intentionally *not* declared as a cross-schema foreign key so
-- that the `ai` schema stays portable; referential integrity to the enterprise
-- tenant table is enforced by the application layer.
--
-- Secrets (API keys, tokens) are never stored here. `credential_ref` holds a
-- reference into the deployment secret manager only.

CREATE OR REPLACE FUNCTION ai.touch_updated_at() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

-- Platform configuration as typed key/value documents (per tenant).
CREATE TABLE IF NOT EXISTS ai.platform_settings (
  tenant_id  bigint      NOT NULL,
  key        text        NOT NULL,
  value      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT platform_settings_pkey PRIMARY KEY (tenant_id, key)
);

-- Provider registry (LLM, embedding, rerank). One row per provider per tenant.
CREATE TABLE IF NOT EXISTS ai.providers (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint      NOT NULL,
  code           text        NOT NULL,
  name           text        NOT NULL,
  kind           text        NOT NULL DEFAULT 'llm',
  base_url       text,
  credential_ref text,
  enabled        boolean     NOT NULL DEFAULT true,
  config         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT providers_uniq UNIQUE (tenant_id, code),
  CONSTRAINT providers_kind_chk CHECK (kind IN ('llm', 'embedding', 'rerank'))
);
CREATE INDEX IF NOT EXISTS providers_tenant_idx ON ai.providers (tenant_id);

-- Model registry under a provider, with capability metadata.
CREATE TABLE IF NOT EXISTS ai.models (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id            bigint      NOT NULL,
  provider_id          bigint      NOT NULL REFERENCES ai.providers(id) ON DELETE CASCADE,
  code                 text        NOT NULL,
  name                 text        NOT NULL,
  capabilities         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  embedding_dimensions integer,
  enabled              boolean     NOT NULL DEFAULT true,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT models_uniq UNIQUE (tenant_id, provider_id, code),
  CONSTRAINT models_embedding_dims_chk
    CHECK (embedding_dimensions IS NULL OR embedding_dimensions > 0)
);
CREATE INDEX IF NOT EXISTS models_tenant_idx ON ai.models (tenant_id);
CREATE INDEX IF NOT EXISTS models_provider_idx ON ai.models (provider_id);

-- Immutable model configuration versions (for reproducibility).
CREATE TABLE IF NOT EXISTS ai.model_versions (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model_id   bigint      NOT NULL REFERENCES ai.models(id) ON DELETE CASCADE,
  version    text        NOT NULL,
  config     jsonb       NOT NULL DEFAULT '{}'::jsonb,
  is_default boolean     NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT model_versions_uniq UNIQUE (model_id, version)
);

-- Prompt templates and their versioned bodies.
CREATE TABLE IF NOT EXISTS ai.prompt_templates (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL,
  code        text        NOT NULL,
  name        text        NOT NULL,
  description text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT prompt_templates_uniq UNIQUE (tenant_id, code)
);
CREATE INDEX IF NOT EXISTS prompt_templates_tenant_idx ON ai.prompt_templates (tenant_id);

CREATE TABLE IF NOT EXISTS ai.prompt_versions (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id bigint      NOT NULL REFERENCES ai.prompt_templates(id) ON DELETE CASCADE,
  version     integer     NOT NULL,
  body        text        NOT NULL,
  variables   jsonb       NOT NULL DEFAULT '[]'::jsonb,
  status      text        NOT NULL DEFAULT 'draft',
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT prompt_versions_uniq UNIQUE (template_id, version),
  CONSTRAINT prompt_versions_status_chk CHECK (status IN ('draft', 'active', 'archived'))
);

-- Agent definitions and their versioned configs.
CREATE TABLE IF NOT EXISTS ai.agents (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL,
  code        text        NOT NULL,
  name        text        NOT NULL,
  description text,
  kind        text        NOT NULL DEFAULT 'knowledge_assistant',
  config      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  enabled     boolean     NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agents_uniq UNIQUE (tenant_id, code)
);
CREATE INDEX IF NOT EXISTS agents_tenant_idx ON ai.agents (tenant_id);

CREATE TABLE IF NOT EXISTS ai.agent_versions (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_id   bigint      NOT NULL REFERENCES ai.agents(id) ON DELETE CASCADE,
  version    integer     NOT NULL,
  definition jsonb       NOT NULL DEFAULT '{}'::jsonb,
  status     text        NOT NULL DEFAULT 'draft',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_versions_uniq UNIQUE (agent_id, version),
  CONSTRAINT agent_versions_status_chk CHECK (status IN ('draft', 'active', 'archived'))
);

-- updated_at maintenance
DROP TRIGGER IF EXISTS trg_platform_settings_updated_at ON ai.platform_settings;
CREATE TRIGGER trg_platform_settings_updated_at BEFORE UPDATE ON ai.platform_settings
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

DROP TRIGGER IF EXISTS trg_providers_updated_at ON ai.providers;
CREATE TRIGGER trg_providers_updated_at BEFORE UPDATE ON ai.providers
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

DROP TRIGGER IF EXISTS trg_models_updated_at ON ai.models;
CREATE TRIGGER trg_models_updated_at BEFORE UPDATE ON ai.models
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

DROP TRIGGER IF EXISTS trg_prompt_templates_updated_at ON ai.prompt_templates;
CREATE TRIGGER trg_prompt_templates_updated_at BEFORE UPDATE ON ai.prompt_templates
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

DROP TRIGGER IF EXISTS trg_agents_updated_at ON ai.agents;
CREATE TRIGGER trg_agents_updated_at BEFORE UPDATE ON ai.agents
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

-- 0012_stage6_agent_platform.sql — Stage 6: Enterprise AI Agent Platform.
--
-- Additive extension of the Phase 9 agent framework. No duplicate execution
-- ledger is introduced: ai.executions remains the single request record.
--
-- Security notes:
--   * Published agent and tool versions are immutable snapshots.
--   * Approval requests bind a canonical operation hash to the exact agent
--     version, step, tool version and normalized arguments.
--   * Agent/tool definitions never contain credentials.

-- --- Agent catalog lifecycle and ownership ------------------------------
ALTER TABLE ai.agents
  ADD COLUMN IF NOT EXISTS owner text,
  ADD COLUMN IF NOT EXISTS team text,
  ADD COLUMN IF NOT EXISTS category text,
  ADD COLUMN IF NOT EXISTS lifecycle_status text NOT NULL DEFAULT 'published',
  ADD COLUMN IF NOT EXISTS current_version_id bigint,
  ADD COLUMN IF NOT EXISTS created_by text,
  ADD COLUMN IF NOT EXISTS updated_by text,
  ADD COLUMN IF NOT EXISTS lock_version integer NOT NULL DEFAULT 1;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'agents_lifecycle_chk') THEN
    ALTER TABLE ai.agents ADD CONSTRAINT agents_lifecycle_chk
      CHECK (lifecycle_status IN
        ('draft', 'validating', 'published', 'deprecated', 'disabled', 'archived'));
  END IF;
END $$;

ALTER TABLE ai.agents
  DROP CONSTRAINT IF EXISTS agents_current_version_fk;
ALTER TABLE ai.agents
  ADD CONSTRAINT agents_current_version_fk
  FOREIGN KEY (current_version_id) REFERENCES ai.agent_versions(id)
  ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS agents_lifecycle_idx
  ON ai.agents (tenant_id, lifecycle_status, category);

-- --- Immutable published agent versions --------------------------------
ALTER TABLE ai.agent_versions
  ADD COLUMN IF NOT EXISTS validation jsonb NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS config_hash text,
  ADD COLUMN IF NOT EXISTS published_at timestamptz,
  ADD COLUMN IF NOT EXISTS published_by text,
  ADD COLUMN IF NOT EXISTS created_by text,
  ADD COLUMN IF NOT EXISTS lock_version integer NOT NULL DEFAULT 1;

ALTER TABLE ai.agent_versions DROP CONSTRAINT IF EXISTS agent_versions_status_chk;
ALTER TABLE ai.agent_versions ADD CONSTRAINT agent_versions_status_chk
  CHECK (status IN
    ('draft', 'validating', 'published', 'active', 'deprecated', 'disabled', 'archived'));

CREATE OR REPLACE FUNCTION ai.guard_agent_version_immutable()
RETURNS trigger AS $$
BEGIN
  IF OLD.status IN ('published', 'active', 'deprecated', 'archived') THEN
    IF NEW.definition IS DISTINCT FROM OLD.definition
       OR NEW.version IS DISTINCT FROM OLD.version THEN
      RAISE EXCEPTION 'published agent versions are immutable';
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_agent_versions_immutable ON ai.agent_versions;
CREATE TRIGGER trg_agent_versions_immutable
  BEFORE UPDATE ON ai.agent_versions
  FOR EACH ROW EXECUTE FUNCTION ai.guard_agent_version_immutable();

-- --- Tool registry ------------------------------------------------------
CREATE TABLE IF NOT EXISTS ai.agent_tools (
  id                 bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          bigint      NOT NULL,
  code               text        NOT NULL,
  name               text        NOT NULL,
  description        text,
  category           text,
  owner              text,
  enabled            boolean     NOT NULL DEFAULT true,
  lifecycle_status   text        NOT NULL DEFAULT 'draft',
  current_version_id bigint,
  created_by         text,
  updated_by         text,
  lock_version       integer     NOT NULL DEFAULT 1,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_tools_code_uniq UNIQUE (tenant_id, code),
  CONSTRAINT agent_tools_lifecycle_chk CHECK (lifecycle_status IN
    ('draft', 'published', 'disabled', 'archived'))
);
CREATE INDEX IF NOT EXISTS agent_tools_tenant_idx
  ON ai.agent_tools (tenant_id, enabled, category);

CREATE TABLE IF NOT EXISTS ai.agent_tool_versions (
  id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tool_id          bigint      NOT NULL REFERENCES ai.agent_tools(id) ON DELETE CASCADE,
  tenant_id        bigint      NOT NULL,
  version          integer     NOT NULL,
  definition       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  status           text        NOT NULL DEFAULT 'draft',
  validation       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  config_hash      text,
  published_at     timestamptz,
  published_by     text,
  created_by       text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_tool_versions_uniq UNIQUE (tool_id, version),
  CONSTRAINT agent_tool_versions_status_chk CHECK (status IN
    ('draft', 'validating', 'published', 'disabled', 'archived'))
);
CREATE INDEX IF NOT EXISTS agent_tool_versions_tool_idx
  ON ai.agent_tool_versions (tool_id, status);

ALTER TABLE ai.agent_tools
  DROP CONSTRAINT IF EXISTS agent_tools_current_version_fk;
ALTER TABLE ai.agent_tools
  ADD CONSTRAINT agent_tools_current_version_fk
  FOREIGN KEY (current_version_id) REFERENCES ai.agent_tool_versions(id)
  ON DELETE SET NULL;

CREATE OR REPLACE FUNCTION ai.guard_agent_tool_version_immutable()
RETURNS trigger AS $$
BEGIN
  IF OLD.status IN ('published', 'disabled', 'archived') THEN
    IF NEW.definition IS DISTINCT FROM OLD.definition
       OR NEW.version IS DISTINCT FROM OLD.version THEN
      RAISE EXCEPTION 'published tool versions are immutable';
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_agent_tool_versions_immutable ON ai.agent_tool_versions;
CREATE TRIGGER trg_agent_tool_versions_immutable
  BEFORE UPDATE ON ai.agent_tool_versions
  FOR EACH ROW EXECUTE FUNCTION ai.guard_agent_tool_version_immutable();

-- Immutable allowlist snapshot created at agent publication.
CREATE TABLE IF NOT EXISTS ai.agent_version_tools (
  id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        bigint      NOT NULL,
  agent_version_id bigint      NOT NULL
    REFERENCES ai.agent_versions(id) ON DELETE CASCADE,
  tool_id          bigint      NOT NULL
    REFERENCES ai.agent_tools(id) ON DELETE CASCADE,
  tool_version_id  bigint      NOT NULL
    REFERENCES ai.agent_tool_versions(id) ON DELETE CASCADE,
  created_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_version_tools_uniq UNIQUE (agent_version_id, tool_id)
);
CREATE INDEX IF NOT EXISTS agent_version_tools_version_idx
  ON ai.agent_version_tools (agent_version_id);

-- --- Durable execution state -------------------------------------------
ALTER TABLE ai.executions
  ADD COLUMN IF NOT EXISTS agent_version_id bigint
    REFERENCES ai.agent_versions(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS parent_execution_id bigint
    REFERENCES ai.executions(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS idempotency_key text,
  ADD COLUMN IF NOT EXISTS plan jsonb NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS budgets jsonb NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS current_step text,
  ADD COLUMN IF NOT EXISTS step_count integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS tool_call_count integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS model_call_count integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS input_hash text,
  ADD COLUMN IF NOT EXISTS input_snapshot jsonb,
  ADD COLUMN IF NOT EXISTS output_snapshot jsonb,
  ADD COLUMN IF NOT EXISTS cancel_requested_at timestamptz,
  ADD COLUMN IF NOT EXISTS lease_owner text,
  ADD COLUMN IF NOT EXISTS lease_expires_at timestamptz,
  ADD COLUMN IF NOT EXISTS started_at timestamptz,
  ADD COLUMN IF NOT EXISTS state_version integer NOT NULL DEFAULT 0;

ALTER TABLE ai.executions DROP CONSTRAINT IF EXISTS executions_status_chk;
ALTER TABLE ai.executions ADD CONSTRAINT executions_status_chk
  CHECK (status IN
    ('pending', 'queued', 'running', 'waiting_approval', 'completed', 'succeeded',
     'failed', 'cancel_requested', 'cancelled', 'timed_out'));

CREATE UNIQUE INDEX IF NOT EXISTS executions_idempotency_uniq
  ON ai.executions (tenant_id, idempotency_key)
  WHERE idempotency_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS executions_worker_idx
  ON ai.executions (status, lease_expires_at, created_at);
CREATE INDEX IF NOT EXISTS executions_agent_version_idx
  ON ai.executions (agent_version_id);

CREATE TABLE IF NOT EXISTS ai.agent_execution_steps (
  id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  execution_id    bigint      NOT NULL REFERENCES ai.executions(id) ON DELETE CASCADE,
  step_key        text        NOT NULL,
  sequence        integer     NOT NULL,
  tool_code       text,
  tool_version_id bigint      REFERENCES ai.agent_tool_versions(id) ON DELETE SET NULL,
  status          text        NOT NULL DEFAULT 'pending',
  attempts        integer     NOT NULL DEFAULT 0,
  max_attempts    integer     NOT NULL DEFAULT 3,
  input_summary   jsonb       NOT NULL DEFAULT '{}'::jsonb,
  output_summary  jsonb       NOT NULL DEFAULT '{}'::jsonb,
  error_class     text,
  error_message   text,
  started_at      timestamptz,
  finished_at     timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_execution_steps_uniq UNIQUE (execution_id, step_key),
  CONSTRAINT agent_execution_steps_status_chk CHECK (status IN
    ('pending', 'running', 'waiting_approval', 'completed', 'failed',
     'skipped', 'cancelled'))
);
CREATE INDEX IF NOT EXISTS agent_execution_steps_exec_idx
  ON ai.agent_execution_steps (tenant_id, execution_id, sequence);

CREATE TABLE IF NOT EXISTS ai.agent_tool_invocations (
  id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  execution_id      bigint      NOT NULL REFERENCES ai.executions(id) ON DELETE CASCADE,
  step_id           bigint      REFERENCES ai.agent_execution_steps(id) ON DELETE SET NULL,
  tool_code         text        NOT NULL,
  tool_version_id   bigint      REFERENCES ai.agent_tool_versions(id) ON DELETE SET NULL,
  status            text        NOT NULL DEFAULT 'running',
  attempt           integer     NOT NULL DEFAULT 1,
  idempotency_key   text,
  outcome_certainty text        NOT NULL DEFAULT 'certain',
  arguments_hash    text,
  arguments_summary jsonb       NOT NULL DEFAULT '{}'::jsonb,
  result_summary    jsonb       NOT NULL DEFAULT '{}'::jsonb,
  error_class       text,
  error_message     text,
  started_at        timestamptz NOT NULL DEFAULT now(),
  finished_at       timestamptz,
  CONSTRAINT agent_tool_invocations_status_chk CHECK (status IN
    ('running', 'succeeded', 'failed', 'denied', 'approval_required', 'cancelled'))
);
CREATE INDEX IF NOT EXISTS agent_tool_invocations_exec_idx
  ON ai.agent_tool_invocations (tenant_id, execution_id);

CREATE TABLE IF NOT EXISTS ai.agent_checkpoints (
  id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     bigint      NOT NULL,
  execution_id  bigint      NOT NULL REFERENCES ai.executions(id) ON DELETE CASCADE,
  sequence      integer     NOT NULL,
  state         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_checkpoints_uniq UNIQUE (execution_id, sequence)
);
CREATE INDEX IF NOT EXISTS agent_checkpoints_exec_idx
  ON ai.agent_checkpoints (tenant_id, execution_id);

CREATE TABLE IF NOT EXISTS ai.agent_approvals (
  id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id           bigint      NOT NULL,
  execution_id        bigint      NOT NULL REFERENCES ai.executions(id) ON DELETE CASCADE,
  step_id             bigint      REFERENCES ai.agent_execution_steps(id) ON DELETE SET NULL,
  step_key            text        NOT NULL,
  tool_code           text        NOT NULL,
  tool_version_id     bigint      REFERENCES ai.agent_tool_versions(id) ON DELETE SET NULL,
  operation_hash      text        NOT NULL,
  target              text,
  input_summary       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  expected_effect     text,
  evidence            jsonb       NOT NULL DEFAULT '[]'::jsonb,
  risk_class          text        NOT NULL,
  requested_by        bigint,
  requested_by_name   text,
  status              text        NOT NULL DEFAULT 'pending',
  expires_at          timestamptz NOT NULL,
  reviewer_actor_id   bigint,
  reviewer_name       text,
  decision_reason     text,
  decided_at          timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT agent_approvals_status_chk CHECK (status IN
    ('pending', 'approved', 'rejected', 'expired', 'cancelled')),
  CONSTRAINT agent_approvals_hash_uniq UNIQUE (tenant_id, operation_hash)
);
CREATE INDEX IF NOT EXISTS agent_approvals_inbox_idx
  ON ai.agent_approvals (tenant_id, status, created_at);
CREATE INDEX IF NOT EXISTS agent_approvals_exec_idx
  ON ai.agent_approvals (tenant_id, execution_id);

CREATE TABLE IF NOT EXISTS ai.agent_artifacts (
  id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     bigint      NOT NULL,
  execution_id  bigint      REFERENCES ai.executions(id) ON DELETE SET NULL,
  artifact_type text        NOT NULL,
  title         text        NOT NULL,
  content       text        NOT NULL,
  created_by    bigint,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS agent_artifacts_tenant_idx
  ON ai.agent_artifacts (tenant_id, created_at DESC);


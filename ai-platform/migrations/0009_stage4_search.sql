-- 0009_stage4_search.sql — Stage 4: saved searches and search history.
--
-- Forward-only. Applied in a single transaction by scripts/migrate.sh.
--
-- Reuse note: the retrieval engine, authorization filter and knowledge tables
-- already exist (0003/0004/0008) and are reused as-is. This migration only adds
-- the user-facing persistence Stage 4 needs: reusable saved searches and a
-- data-minimized, per-user search history.
--
-- Authorization note: every row is tenant- and actor-scoped. History and saved
-- searches are *personal*: a row is only ever read or removed for the exact
-- actor that created it (`actor_id IS NOT DISTINCT FROM ...`). Storing a query
-- never grants access to its results — history is replayed by re-running the
-- live retrieval pipeline, so revoked access is never resurrected from a stored
-- query.

-- --- Saved searches -----------------------------------------------------
-- A saved search stores the *request* (query + mode + filters + sort), never a
-- frozen result set, so replaying it always applies current ACLs/classification.
CREATE TABLE IF NOT EXISTS ai.search_saved (
  id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id  bigint      NOT NULL,
  actor_id   bigint,
  name       text        NOT NULL,
  query      text        NOT NULL,
  mode       text        NOT NULL DEFAULT 'hybrid',
  filters    jsonb       NOT NULL DEFAULT '[]'::jsonb,
  sort       text        NOT NULL DEFAULT 'relevance',
  metadata   jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT search_saved_mode_chk
    CHECK (mode IN ('hybrid', 'lexical', 'semantic')),
  CONSTRAINT search_saved_sort_chk
    CHECK (sort IN ('relevance', 'recency', 'title')),
  CONSTRAINT search_saved_name_chk CHECK (length(btrim(name)) > 0)
);
CREATE INDEX IF NOT EXISTS search_saved_owner_idx
  ON ai.search_saved (tenant_id, actor_id, updated_at DESC)
  WHERE deleted_at IS NULL;

-- --- Search history -----------------------------------------------------
-- Data-minimized: the query text, the retrieval mode/filters used, and the
-- result count only. No result content, snippets or identifiers are stored, so
-- a history row can never leak document contents.
CREATE TABLE IF NOT EXISTS ai.search_history (
  id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    bigint      NOT NULL,
  actor_id     bigint,
  query        text        NOT NULL,
  mode         text        NOT NULL DEFAULT 'hybrid',
  filters      jsonb       NOT NULL DEFAULT '[]'::jsonb,
  sort         text        NOT NULL DEFAULT 'relevance',
  result_count integer     NOT NULL DEFAULT 0,
  fallback     boolean     NOT NULL DEFAULT false,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT search_history_mode_chk
    CHECK (mode IN ('hybrid', 'lexical', 'semantic')),
  CONSTRAINT search_history_sort_chk
    CHECK (sort IN ('relevance', 'recency', 'title')),
  CONSTRAINT search_history_result_count_chk CHECK (result_count >= 0)
);
CREATE INDEX IF NOT EXISTS search_history_owner_idx
  ON ai.search_history (tenant_id, actor_id, created_at DESC);

-- updated_at maintenance (reuses the shared touch function from 0008)
DROP TRIGGER IF EXISTS trg_search_saved_updated_at ON ai.search_saved;
CREATE TRIGGER trg_search_saved_updated_at
  BEFORE UPDATE ON ai.search_saved
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

-- --- updated_at triggers ------------------------------------------------
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'mfg_plants', 'mfg_production_lines', 'mfg_work_centres', 'mfg_processes',
    'mfg_process_revisions', 'mfg_operations', 'mfg_operation_consumptions',
    'mfg_work_instructions', 'mfg_resources', 'mfg_production_versions',
    'quality_issues', 'quality_inspections', 'quality_root_causes',
    'quality_actions', 'quality_supplier_issues'
  ] LOOP
    EXECUTE format(
      'DROP TRIGGER IF EXISTS trg_%I_updated_at ON ai.%I', tbl, tbl
    );
    EXECUTE format(
      'CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON ai.%I '
      'FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at()', tbl, tbl
    );
  END LOOP;
END
$$;

-- --- RLS: direct tenant ownership ---------------------------------------
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'mfg_plants', 'mfg_production_lines', 'mfg_work_centres', 'mfg_processes',
    'mfg_process_revisions', 'mfg_operations', 'mfg_operation_dependencies',
    'mfg_operation_consumptions', 'mfg_work_instructions', 'mfg_resources',
    'mfg_production_versions', 'quality_issues', 'quality_inspections',
    'quality_inspection_results', 'quality_root_causes', 'quality_actions',
    'quality_supplier_issues'
  ] LOOP
    EXECUTE format('ALTER TABLE ai.%I ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE ai.%I FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON ai.%I', tbl);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON ai.%I FOR ALL TO PUBLIC '
      'USING (ai.tenant_isolation_allows(tenant_id)) '
      'WITH CHECK (ai.tenant_isolation_allows(tenant_id))',
      tbl
    );
  END LOOP;
END
$$;


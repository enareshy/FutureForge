-- 0025_stage9_manufacturing_quality.sql — Manufacturing & Quality (Step 7).
--
-- Additive only. Adds tenant-scoped manufacturing structure (plants, production
-- lines, work centres, process plans/revisions, operations, dependencies,
-- operation consumption, work instructions, resources, production versions) and
-- quality records (issues/nonconformances, inspections/results, root causes,
-- corrective/preventive actions, supplier quality).
--
-- These are *domain* records that live alongside the knowledge graph. Each row
-- may carry a `graph_entity_id` pointing at the graph entity that represents it,
-- so the digital thread, traversal and impact engines keep working without a
-- second graph model. Multi-level manufacturing structure is stored here, not
-- duplicated in the graph.
--
-- Identity:
--   * mfg_plants               UNIQUE (tenant_id, plant_key)
--   * mfg_production_lines     UNIQUE (tenant_id, plant_id, line_key)
--   * mfg_work_centres         UNIQUE (tenant_id, plant_id, work_centre_key)
--   * mfg_processes            UNIQUE (tenant_id, process_type, process_key)
--   * mfg_process_revisions    UNIQUE (tenant_id, process_id, revision)
--   * mfg_operations           UNIQUE (tenant_id, process_id, operation_key)
--   * mfg_work_instructions    UNIQUE (tenant_id, instruction_key)
--   * mfg_resources            UNIQUE (tenant_id, resource_key)
--   * mfg_production_versions  UNIQUE (tenant_id, item_id, version_key)
--   * quality_issues           UNIQUE (tenant_id, issue_key)
--   * quality_inspections      UNIQUE (tenant_id, inspection_key)
--   * quality_actions          UNIQUE (tenant_id, action_key)
--
-- RLS: every table carries an explicit tenant_id and reuses the same FORCE ROW
-- LEVEL SECURITY policy as the rest of the `ai` schema.

-- --- Manufacturing sites -------------------------------------------------

-- 0011_stage5_copilot.sql — Stage 5: Enterprise AI Copilot.
--
-- Additive extension of the Stage 3 assistant conversation model. No duplicate
-- conversation/message/citation tables are introduced.
--
-- Authorization note: every conversation, message, context reference and
-- summary is tenant-scoped. Context references store stable identifiers and
-- normalized metadata only; source content is never copied into these tables.

-- --- Message task/generation metadata ----------------------------------
-- `generation_status` completes the lifecycle (pending -> streaming ->
-- completed|cancelled|failed). Existing rows are complete by definition.
ALTER TABLE ai.assistant_messages
  ADD COLUMN IF NOT EXISTS task_type text
    CHECK (task_type IS NULL
           OR task_type IN ('ask', 'summarize', 'explain', 'compare', 'extract'));
ALTER TABLE ai.assistant_messages
  ADD COLUMN IF NOT EXISTS generation_status text NOT NULL DEFAULT 'completed'
    CHECK (generation_status IN
           ('pending', 'streaming', 'completed', 'cancelled', 'failed'));
ALTER TABLE ai.assistant_messages
  ADD COLUMN IF NOT EXISTS prompt_version text;
ALTER TABLE ai.assistant_messages
  ADD COLUMN IF NOT EXISTS parent_message_id bigint
    REFERENCES ai.assistant_messages(id) ON DELETE SET NULL;
ALTER TABLE ai.assistant_messages
  ADD COLUMN IF NOT EXISTS cancelled_at timestamptz;

CREATE INDEX IF NOT EXISTS assistant_messages_status_idx
  ON ai.assistant_messages (tenant_id, conversation_id, generation_status);

-- --- Per-message authorized context references -------------------------
-- A context reference is a stable pointer to an authorized source record plus
-- normalized metadata returned by an adapter. It deliberately stores no source
-- content, so revoking access to the source also removes the usable content.
CREATE TABLE IF NOT EXISTS ai.assistant_context_refs (
  id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        bigint      NOT NULL,
  conversation_id  bigint      NOT NULL
    REFERENCES ai.assistant_conversations(id) ON DELETE CASCADE,
  message_id       bigint      NOT NULL
    REFERENCES ai.assistant_messages(id) ON DELETE CASCADE,
  context_type     text        NOT NULL,
  object_id        text        NOT NULL,
  display_name     text,
  source_system    text,
  revision         text,
  lifecycle_state  text,
  metadata         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  provenance       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assistant_context_refs_uniq
    UNIQUE (message_id, context_type, object_id)
);
CREATE INDEX IF NOT EXISTS assistant_context_refs_conversation_idx
  ON ai.assistant_context_refs (tenant_id, conversation_id);
CREATE INDEX IF NOT EXISTS assistant_context_refs_message_idx
  ON ai.assistant_context_refs (message_id);

-- --- Derived conversation summaries ------------------------------------
-- One active derived summary per conversation. It is context, never an
-- authoritative enterprise record, and can be regenerated from messages.
CREATE TABLE IF NOT EXISTS ai.assistant_conversation_summaries (
  conversation_id    bigint      PRIMARY KEY
    REFERENCES ai.assistant_conversations(id) ON DELETE CASCADE,
  tenant_id          bigint      NOT NULL,
  summary            text        NOT NULL,
  through_message_id bigint
    REFERENCES ai.assistant_messages(id) ON DELETE SET NULL,
  token_estimate     integer,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS assistant_conversation_summaries_tenant_idx
  ON ai.assistant_conversation_summaries (tenant_id);

DROP TRIGGER IF EXISTS trg_assistant_conversation_summaries_updated_at
  ON ai.assistant_conversation_summaries;
CREATE TRIGGER trg_assistant_conversation_summaries_updated_at
  BEFORE UPDATE ON ai.assistant_conversation_summaries
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

-- --- Feedback categories ------------------------------------------------
-- Keep the numeric rating (backward compatible) and add a bounded category for
-- quality analytics. Categories are validated, not free text.
ALTER TABLE ai.feedback
  ADD COLUMN IF NOT EXISTS category text
    CHECK (category IS NULL
           OR category IN ('helpful', 'not_helpful', 'incorrect',
                           'missing_information', 'poor_citations', 'other'));
CREATE INDEX IF NOT EXISTS feedback_category_idx
  ON ai.feedback (tenant_id, category, created_at DESC);

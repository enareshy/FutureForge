-- 0010_stage4_duplicates.sql — Stage 4: duplicate/conflict findings.
--
-- Forward-only. Applied in a single transaction by scripts/migrate.sh.
--
-- Detection is advisory: findings are *review records* describing a possible
-- duplicate (same content) or conflict (same identifier, different content)
-- between two documents. Nothing is merged, overwritten or deleted; a human
-- reviewer dismisses or resolves each finding explicitly.
--
-- Authorization note: findings are tenant-scoped and only expose minimal
-- document metadata (ids/identifiers/titles), never content. Document FK
-- cascades remove findings when either side is deleted, so a stale finding can
-- never reference content that no longer exists.

CREATE TABLE IF NOT EXISTS ai.search_duplicate_findings (
  id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     bigint      NOT NULL,
  -- Canonical pair key (`<document_a_id>:<document_b_id>`, a < b) so rescanning
  -- updates the same finding instead of creating duplicates.
  dedupe_key    text        NOT NULL,
  kind          text        NOT NULL,
  match_type    text        NOT NULL,
  confidence    numeric(5, 4) NOT NULL,
  document_a_id bigint      NOT NULL REFERENCES ai.documents(id) ON DELETE CASCADE,
  document_b_id bigint      NOT NULL REFERENCES ai.documents(id) ON DELETE CASCADE,
  evidence      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  status        text        NOT NULL DEFAULT 'open',
  note          text,
  reviewed_by   bigint,
  reviewed_at   timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT search_dup_kind_chk
    CHECK (kind IN ('duplicate', 'conflict')),
  CONSTRAINT search_dup_match_chk
    CHECK (match_type IN ('checksum', 'external_id', 'title')),
  CONSTRAINT search_dup_status_chk
    CHECK (status IN ('open', 'dismissed', 'resolved')),
  CONSTRAINT search_dup_confidence_chk
    CHECK (confidence >= 0 AND confidence <= 1),
  CONSTRAINT search_dup_order_chk
    CHECK (document_a_id < document_b_id),
  CONSTRAINT search_dup_uniq UNIQUE (tenant_id, dedupe_key)
);
CREATE INDEX IF NOT EXISTS search_dup_status_idx
  ON ai.search_duplicate_findings (tenant_id, status, confidence DESC);
CREATE INDEX IF NOT EXISTS search_dup_doc_a_idx
  ON ai.search_duplicate_findings (tenant_id, document_a_id);
CREATE INDEX IF NOT EXISTS search_dup_doc_b_idx
  ON ai.search_duplicate_findings (tenant_id, document_b_id);

DROP TRIGGER IF EXISTS trg_search_duplicate_findings_updated_at
  ON ai.search_duplicate_findings;
CREATE TRIGGER trg_search_duplicate_findings_updated_at
  BEFORE UPDATE ON ai.search_duplicate_findings
  FOR EACH ROW EXECUTE FUNCTION ai.touch_updated_at();

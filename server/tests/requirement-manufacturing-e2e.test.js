// End-to-end acceptance test for the Requirement -> Manufacturing traceability
// layer. It builds the full chain (Requirement -> EBOM -> MBOM -> BOP ->
// Operation -> Work center, CTQ) using only the existing PDM/BOM/Object/
// Classification engines plus this layer's composition seams, then asserts the
// projections (matrix, coverage, gaps, impact, navigation) and the REST surface
// that the frontend workspace consumes.
